//! FreeBSD-aligned TCP SYN cache (K276).
//!
//! The cache keeps embryonic connections in bounded hash buckets until the final ACK of the
//! three-way handshake, so a SYN flood cannot allocate a full socket per spoofed source.  The
//! behaviour is a Rust port of FreeBSD `sys/netinet/tcp_syncache.c` at
//! `133344405f532bd54ff3629a77d4c4e062f01fdb`.
//!
//! The stack already owns packet output, ISN generation and the connection state machine.  This
//! module therefore keeps the donor's state and timers but leaves the effects to the caller:
//!
//! * `insert` reports a new entry or a duplicate SYN and its timeout is reset;
//! * `promote` validates the final ACK exactly as `syncache_expand` does and returns the entry
//!   that the caller turns into a `TcpConnection`;
//! * `abort` validates an RST against the receive window;
//! * `poll` returns the entries whose SYN/ACK retransmit is due and removes the ones whose
//!   retransmit budget is exhausted.
//!
//! ISS generation stays in `listen.rs` (the existing RFC 6528/cookie source) and is passed to
//! `insert`, so there is one ISN generator for the stack.  FreeBSD generates it in
//! `syncache_add`; that is the only behavioural split, recorded in the report.

#![allow(dead_code)] // Wired into lib.rs, but the tcp_state call sites are a later integration.

use alloc::collections::VecDeque;
use alloc::vec::Vec;

/// Default number of hash buckets (`TCP_SYNCACHE_HASHSIZE`).
pub const SYNCACHE_HASHSIZE: usize = 512;
/// Default entries per bucket (`TCP_SYNCACHE_BUCKETLIMIT`).
pub const SYNCACHE_BUCKETLIMIT: usize = 30;
/// Default SYN/ACK retransmit budget (`SYNCACHE_MAXREXMTS`).
pub const SYNCACHE_MAXREXMTS: u8 = 3;
/// Largest unscaled TCP window (`TCP_MAXWIN`).
pub const TCP_MAXWIN: u32 = 65_535;
/// Largest window-scale shift (`TCP_MAX_WINSHIFT`).
pub const TCP_MAX_WINSHIFT: u8 = 14;

/// FreeBSD `tcp_backoff[]`: the SYN/ACK retransmit multiplier per attempt.
const BACKOFF: [u32; 13] = [1, 2, 4, 8, 16, 32, 64, 128, 256, 512, 512, 512, 512];

/// An IP address in the cache key.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Address {
    /// IPv4 address.
    V4([u8; 4]),
    /// IPv6 address.
    V6([u8; 16]),
}

/// One side of a connection.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct Endpoint {
    /// Address.
    pub address: Address,
    /// TCP port.
    pub port: u16,
}

/// The four-tuple that indexes the cache.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct Key {
    /// Local address and port.
    pub local: Endpoint,
    /// Remote address and port.
    pub remote: Endpoint,
}

/// TCP options carried by the initial SYN.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct SynOptions {
    /// Peer maximum segment size, if present.
    pub mss: Option<u16>,
    /// Peer window-scale shift, if present.
    pub window_scale: Option<u8>,
    /// SACK-permitted option present.
    pub sack_permitted: bool,
    /// Peer timestamp value, if present.
    pub timestamp: Option<u32>,
    /// ECN was negotiated for this handshake.
    pub ecn: bool,
    /// The listener asks for no TCP options (`TF_NOOPT`).
    pub no_options: bool,
}

/// The SYN that creates a cache entry.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct SynRequest {
    /// Connection key.
    pub key: Key,
    /// Peer initial receive sequence (`th_seq`).
    pub irs: u32,
    /// Our initial send sequence; generated by the stack's existing ISN/cookie source.
    pub iss: u32,
    /// Receive buffer space advertised in the SYN/ACK.
    pub receive_window: u32,
    /// Parsed TCP options.
    pub options: SynOptions,
    /// Received IP TTL / hop limit.
    pub ip_ttl: u8,
    /// Received IP TOS / traffic class.
    pub ip_tos: u8,
}

/// One embryonic connection.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SyncacheEntry {
    /// Connection key.
    pub key: Key,
    /// Peer initial sequence.
    pub irs: u32,
    /// Our initial sequence.
    pub iss: u32,
    /// Window advertised in our SYN/ACK, already clipped to `TCP_MAXWIN`.
    pub receive_window: u16,
    /// Peer maximum segment size, if the SYN carried one.
    pub peer_mss: Option<u16>,
    /// Peer's requested window scale (`sc_requested_s_scale`).
    pub requested_s_scale: u8,
    /// Our requested window scale (`sc_requested_r_scale`).
    pub requested_r_scale: u8,
    /// Window scaling was negotiated.
    pub window_scale: bool,
    /// Timestamp to reflect; `None` when timestamps were not negotiated.
    pub timestamp: Option<u32>,
    /// SACK was permitted.
    pub sack: bool,
    /// ECN was negotiated.
    pub ecn: bool,
    /// The listener disabled all options.
    pub no_options: bool,
    /// Received IP TTL / hop limit.
    pub ip_ttl: u8,
    /// Received IP TOS / traffic class.
    pub ip_tos: u8,
    /// SYN/ACK retransmits already performed.
    pub rxmits: u8,
    /// Monotonic milliseconds of the next retransmit or expiry.
    pub next_timeout_ms: u64,
    /// Monotonic milliseconds when the entry was created.
    pub created_ms: u64,
}

/// Cache limits and timers.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct SyncacheConfig {
    /// Number of hash buckets.
    pub buckets: usize,
    /// Entries allowed in one bucket.
    pub bucket_limit: usize,
    /// Entries allowed in the whole cache.
    pub cache_limit: usize,
    /// First SYN/ACK retransmit timeout in milliseconds.
    pub initial_rto_ms: u32,
    /// Lower bound for a retransmit timeout.
    pub rto_min_ms: u32,
    /// Upper bound for a retransmit timeout.
    pub rto_max_ms: u32,
    /// Retransmits before the entry is stale.
    pub max_retransmits: u8,
    /// Socket buffer ceiling used to pick our window-scale value.
    pub max_sockbuf: u32,
}

impl Default for SyncacheConfig {
    fn default() -> Self {
        Self {
            buckets: SYNCACHE_HASHSIZE,
            bucket_limit: SYNCACHE_BUCKETLIMIT,
            cache_limit: SYNCACHE_HASHSIZE * SYNCACHE_BUCKETLIMIT,
            initial_rto_ms: 1_000,
            rto_min_ms: 200,
            rto_max_ms: 60_000,
            max_retransmits: SYNCACHE_MAXREXMTS,
            max_sockbuf: 262_144,
        }
    }
}

/// Counters mirroring the FreeBSD `tcps_sc_*` namespace.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct SyncacheStats {
    /// Entries inserted.
    pub added: u64,
    /// Duplicate SYNs that refreshed an existing entry.
    pub duplicate_syn: u64,
    /// Entries evicted by a limit or a failed response.
    pub dropped: u64,
    /// Entries promoted by the final ACK.
    pub completed: u64,
    /// Entries removed after the retransmit budget was exhausted.
    pub stale: u64,
    /// Entries removed by a valid RST.
    pub reset: u64,
    /// SYN/ACK retransmits scheduled.
    pub retransmits: u64,
    /// Evictions caused by the per-bucket limit.
    pub bucket_overflow: u64,
    /// Evictions caused by the global cache limit.
    pub cache_overflow: u64,
    /// ACKs whose `th_ack` did not match `ISS + 1`.
    pub bad_ack: u64,
    /// RSTs that did not match the receive window.
    pub bad_rst: u64,
    /// Challenge ACKs required by an out-of-window segment.
    pub challenge: u64,
    /// Segments dropped for a timestamp problem.
    pub timestamp_drops: u64,
}

/// Result of a SYN insertion.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum InsertOutcome {
    /// A new entry was inserted in this bucket.
    Inserted {
        /// Bucket index.
        bucket: usize,
    },
    /// A duplicate SYN refreshed an existing entry and reset its timer.
    Duplicate {
        /// The entry's ISS.
        iss: u32,
        /// The retransmit counter was reset to zero.
        rxmits: u8,
    },
    /// The global cache limit rejected the entry.
    Rejected,
}

/// Final ACK presented for promotion.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct AckRequest {
    /// Connection key.
    pub key: Key,
    /// Segment sequence (`th_seq`).
    pub seq: u32,
    /// Segment acknowledgement (`th_ack`).
    pub ack: u32,
    /// Peer's advertised window.
    pub window: u16,
    /// Timestamp value, if the segment carried one.
    pub timestamp: Option<u32>,
}

/// Result of trying to promote an entry.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum PromoteOutcome {
    /// A valid final ACK removed the entry; the caller builds the TCB from it and takes the
    /// peer's advertised window from the ACK.
    Promoted {
        /// The embryonic connection data.
        entry: SyncacheEntry,
        /// Peer window from the final ACK (`th_win`).
        window: u16,
    },
    /// No entry matches the four-tuple.
    Missing,
    /// `th_ack` did not equal `ISS + 1`; send a RST and keep the entry.
    BadAck,
    /// `th_seq` was outside `(IRS, IRS + WND]`; send a challenge ACK.
    BadSequence,
    /// Timestamps were negotiated but the ACK carried none; silently drop.
    MissingTimestamp,
    /// The ACK timestamp was older than the reflected value; drop.
    StaleTimestamp,
}

/// Result of an RST.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum AbortOutcome {
    /// A valid RST removed the entry.
    Removed,
    /// The sequence was in the window but not `IRS + 1`; send a challenge ACK.
    Challenge,
    /// No matching entry or an out-of-window RST.
    Ignored,
}

/// A timer event returned by [`Syncache::poll`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SyncacheAction {
    /// Retransmit the SYN/ACK for this key.
    Retransmit(Key),
    /// The retransmit budget is exhausted; the entry was removed.
    Expired(Key),
}

/// The bounded SYN cache.
#[derive(Clone, Debug)]
pub struct Syncache {
    config: SyncacheConfig,
    buckets: Vec<VecDeque<SyncacheEntry>>,
    len: usize,
    stats: SyncacheStats,
}

impl Syncache {
    /// Create a cache with `config`.  Zero limits are raised to one.
    #[must_use]
    pub fn new(config: SyncacheConfig) -> Self {
        let buckets = config.buckets.max(1);
        let bucket_limit = config.bucket_limit.max(1);
        let cache_limit = config.cache_limit.max(1);
        let config = SyncacheConfig {
            buckets,
            bucket_limit,
            cache_limit,
            initial_rto_ms: config.initial_rto_ms.max(1),
            rto_min_ms: config.rto_min_ms.max(1),
            rto_max_ms: config.rto_max_ms.max(config.rto_min_ms.max(1)),
            max_retransmits: config.max_retransmits,
            max_sockbuf: config.max_sockbuf.max(TCP_MAXWIN),
        };
        Self {
            config,
            buckets: (0..buckets).map(|_| VecDeque::new()).collect(),
            len: 0,
            stats: SyncacheStats::default(),
        }
    }

    /// The active configuration.
    #[must_use]
    pub fn config(&self) -> SyncacheConfig {
        self.config
    }

    /// The counters.
    #[must_use]
    pub fn stats(&self) -> SyncacheStats {
        self.stats
    }

    /// Number of live entries.
    #[must_use]
    pub fn len(&self) -> usize {
        self.len
    }

    /// Whether the cache has no live entries.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.len == 0
    }

    /// Number of entries in one bucket.
    #[must_use]
    pub fn bucket_len(&self, bucket: usize) -> usize {
        self.buckets.get(bucket).map_or(0, VecDeque::len)
    }

    /// All live entries, bucket order and newest first inside a bucket.
    pub fn entries(&self) -> impl Iterator<Item = &SyncacheEntry> {
        self.buckets.iter().flat_map(|bucket| bucket.iter())
    }

    /// Look up a live entry by four-tuple.
    #[must_use]
    pub fn lookup(&self, key: &Key) -> Option<&SyncacheEntry> {
        let bucket = self.bucket_index(key);
        self.buckets[bucket].iter().find(|entry| entry.key == *key)
    }

    /// Insert a SYN.  A duplicate refreshes the existing entry and resets its timer.
    pub fn insert(&mut self, syn: SynRequest, now_ms: u64) -> InsertOutcome {
        let bucket = self.bucket_index(&syn.key);
        if let Some(index) = self.buckets[bucket]
            .iter()
            .position(|entry| entry.key == syn.key)
        {
            let entry = &mut self.buckets[bucket][index];
            // FreeBSD `syncache_add` keeps the original MSS/scale/SACK but refreshes the
            // timestamp when the new SYN carries one and clears it when it does not.
            if entry.timestamp.is_some() && syn.options.timestamp.is_some() {
                entry.timestamp = syn.options.timestamp;
            } else {
                entry.timestamp = None;
            }
            // FreeBSD only re-evaluates ECN when the entry negotiated it.
            if entry.ecn {
                entry.ecn = syn.options.ecn;
            }
            entry.rxmits = 0;
            entry.next_timeout_ms = now_ms.saturating_add(u64::from(self.config.initial_rto_ms));
            self.stats.duplicate_syn = self.stats.duplicate_syn.saturating_add(1);
            return InsertOutcome::Duplicate {
                iss: entry.iss,
                rxmits: entry.rxmits,
            };
        }

        if self.buckets[bucket].len() >= self.config.bucket_limit {
            self.buckets[bucket].pop_back();
            self.len = self.len.saturating_sub(1);
            self.stats.dropped = self.stats.dropped.saturating_add(1);
            self.stats.bucket_overflow = self.stats.bucket_overflow.saturating_add(1);
        }
        while self.len >= self.config.cache_limit {
            let Some(victim) = self.oldest_bucket() else {
                self.stats.dropped = self.stats.dropped.saturating_add(1);
                self.stats.cache_overflow = self.stats.cache_overflow.saturating_add(1);
                return InsertOutcome::Rejected;
            };
            self.buckets[victim].pop_back();
            self.len = self.len.saturating_sub(1);
            self.stats.dropped = self.stats.dropped.saturating_add(1);
            self.stats.cache_overflow = self.stats.cache_overflow.saturating_add(1);
        }

        let mut requested_r_scale = 0u8;
        while requested_r_scale < TCP_MAX_WINSHIFT
            && (TCP_MAXWIN << requested_r_scale) < self.config.max_sockbuf
        {
            requested_r_scale = requested_r_scale.saturating_add(1);
        }
        let receive_window = syn.receive_window.min(TCP_MAXWIN) as u16;
        let options = syn.options;
        let entry = SyncacheEntry {
            key: syn.key,
            irs: syn.irs,
            iss: syn.iss,
            receive_window,
            peer_mss: options.mss,
            requested_s_scale: options.window_scale.unwrap_or(0),
            requested_r_scale,
            window_scale: options.window_scale.is_some() && !options.no_options,
            timestamp: if options.no_options {
                None
            } else {
                options.timestamp
            },
            sack: options.sack_permitted && !options.no_options,
            ecn: options.ecn,
            no_options: options.no_options,
            ip_ttl: syn.ip_ttl,
            ip_tos: syn.ip_tos,
            rxmits: 0,
            next_timeout_ms: now_ms.saturating_add(u64::from(self.config.initial_rto_ms)),
            created_ms: now_ms,
        };
        self.buckets[bucket].push_front(entry);
        self.len = self.len.saturating_add(1);
        self.stats.added = self.stats.added.saturating_add(1);
        InsertOutcome::Inserted { bucket }
    }

    /// Validate the final ACK and remove the promoted entry.
    pub fn promote(&mut self, ack: AckRequest) -> PromoteOutcome {
        let bucket = self.bucket_index(&ack.key);
        let Some(index) = self.buckets[bucket]
            .iter()
            .position(|entry| entry.key == ack.key)
        else {
            return PromoteOutcome::Missing;
        };
        let entry = &self.buckets[bucket][index];

        // FreeBSD `syncache_expand`: SEG.ACK must be ISS + 1.
        if ack.ack != entry.iss.wrapping_add(1) {
            self.stats.bad_ack = self.stats.bad_ack.saturating_add(1);
            return PromoteOutcome::BadAck;
        }
        // SEG.SEQ must be in (IRS, IRS + WND].
        let last = entry.irs.wrapping_add(u32::from(entry.receive_window));
        if !seq_gt(ack.seq, entry.irs) || seq_gt(ack.seq, last) {
            self.stats.challenge = self.stats.challenge.saturating_add(1);
            return PromoteOutcome::BadSequence;
        }

        // RFC 7323: timestamps are mandatory once negotiated; a stale TSval is dropped.
        if let Some(reflected) = entry.timestamp {
            match ack.timestamp {
                None => {
                    self.stats.timestamp_drops = self.stats.timestamp_drops.saturating_add(1);
                    return PromoteOutcome::MissingTimestamp;
                }
                Some(value) if timestamp_lt(value, reflected) => {
                    self.stats.timestamp_drops = self.stats.timestamp_drops.saturating_add(1);
                    return PromoteOutcome::StaleTimestamp;
                }
                Some(_) => {}
            }
        }

        let Some(entry) = self.buckets[bucket].remove(index) else {
            return PromoteOutcome::Missing;
        };
        self.len = self.len.saturating_sub(1);
        self.stats.completed = self.stats.completed.saturating_add(1);
        PromoteOutcome::Promoted {
            entry,
            window: ack.window,
        }
    }

    /// Validate and apply an RST.
    pub fn abort(&mut self, key: &Key, seq: u32) -> AbortOutcome {
        let bucket = self.bucket_index(key);
        let Some(index) = self.buckets[bucket]
            .iter()
            .position(|entry| entry.key == *key)
        else {
            self.stats.bad_rst = self.stats.bad_rst.saturating_add(1);
            return AbortOutcome::Ignored;
        };
        let entry = &self.buckets[bucket][index];
        let first = entry.irs.wrapping_add(1);
        let in_window = if entry.receive_window == 0 {
            seq == first
        } else {
            let last = first.wrapping_add(u32::from(entry.receive_window));
            !seq_lt(seq, first) && seq_lt(seq, last)
        };
        if !in_window {
            self.stats.bad_rst = self.stats.bad_rst.saturating_add(1);
            return AbortOutcome::Ignored;
        }
        // FreeBSD only drops on `IRS + 1` by default; a reset elsewhere in the window gets a
        // challenge ACK so a spoofed RST cannot abort the handshake.
        if seq != first {
            self.stats.bad_rst = self.stats.bad_rst.saturating_add(1);
            return AbortOutcome::Challenge;
        }
        self.buckets[bucket].remove(index);
        self.len = self.len.saturating_sub(1);
        self.stats.reset = self.stats.reset.saturating_add(1);
        AbortOutcome::Removed
    }

    /// Run the SYN/ACK timer at `now_ms`.
    pub fn poll(&mut self, now_ms: u64) -> Vec<SyncacheAction> {
        let mut actions = Vec::new();
        let config = self.config;
        for bucket in &mut self.buckets {
            let mut index = 0;
            while index < bucket.len() {
                if bucket[index].next_timeout_ms > now_ms {
                    index += 1;
                    continue;
                }
                let key = bucket[index].key;
                if bucket[index].rxmits > self.config.max_retransmits {
                    bucket.remove(index);
                    self.len = self.len.saturating_sub(1);
                    self.stats.stale = self.stats.stale.saturating_add(1);
                    actions.push(SyncacheAction::Expired(key));
                    continue;
                }
                bucket[index].rxmits = bucket[index].rxmits.saturating_add(1);
                let delta = retransmit_delay(config, bucket[index].rxmits);
                bucket[index].next_timeout_ms = now_ms.saturating_add(u64::from(delta));
                self.stats.retransmits = self.stats.retransmits.saturating_add(1);
                actions.push(SyncacheAction::Retransmit(key));
                index += 1;
            }
        }
        actions
    }

    /// Earliest pending timeout, if any.
    #[must_use]
    pub fn next_deadline(&self) -> Option<u64> {
        self.entries().map(|entry| entry.next_timeout_ms).min()
    }

    /// Remove every entry (the FreeBSD `syncache_pause` path).
    pub fn clear(&mut self) -> usize {
        let removed = self.len;
        for bucket in &mut self.buckets {
            bucket.clear();
        }
        self.len = 0;
        removed
    }

    fn bucket_index(&self, key: &Key) -> usize {
        usize::try_from(hash_key(key) % self.config.buckets as u64).unwrap_or(0)
    }

    fn oldest_bucket(&self) -> Option<usize> {
        self.buckets
            .iter()
            .enumerate()
            .filter(|(_, bucket)| !bucket.is_empty())
            .min_by_key(|(_, bucket)| bucket.back().map_or(0, |entry| entry.created_ms))
            .map(|(index, _)| index)
    }
}

fn retransmit_delay(config: SyncacheConfig, rxmits: u8) -> u32 {
    let shift = usize::from(rxmits).min(BACKOFF.len() - 1);
    let value = u64::from(config.initial_rto_ms)
        .saturating_mul(u64::from(BACKOFF[shift]))
        .min(u64::from(u32::MAX)) as u32;
    value.clamp(config.rto_min_ms, config.rto_max_ms)
}

fn hash_key(key: &Key) -> u64 {
    let mut hash = 0xcbf2_9ce4_8422_2325u64;
    hash_endpoint(&mut hash, &key.local);
    hash_endpoint(&mut hash, &key.remote);
    mix(hash)
}

fn hash_endpoint(hash: &mut u64, endpoint: &Endpoint) {
    match endpoint.address {
        Address::V4(octets) => {
            for octet in octets {
                *hash = (*hash ^ u64::from(octet)).wrapping_mul(0x100_0000_01b3);
            }
        }
        Address::V6(octets) => {
            for octet in octets {
                *hash = (*hash ^ u64::from(octet)).wrapping_mul(0x100_0000_01b3);
            }
        }
    }
    *hash = (*hash ^ u64::from(endpoint.port)).wrapping_mul(0x100_0000_01b3);
}

fn mix(mut value: u64) -> u64 {
    value ^= value >> 33;
    value = value.wrapping_mul(0xff51_afd7_ed55_8ccd);
    value ^= value >> 33;
    value = value.wrapping_mul(0xc4ce_b9fe_1a85_ec53);
    value ^ (value >> 33)
}

fn seq_gt(left: u32, right: u32) -> bool {
    (left.wrapping_sub(right) as i32) > 0
}

fn seq_lt(left: u32, right: u32) -> bool {
    seq_gt(right, left)
}

fn timestamp_lt(left: u32, right: u32) -> bool {
    (left.wrapping_sub(right) as i32) < 0
}
