//! `LS_COLORS` and `LESS_TERMCAP_*` adapters.

use alloc::string::{String, ToString};

use crate::ansi::{Depth, ansi16, xterm256};
use crate::palette::{Palette, Rgb, Role};

fn params(colour: Rgb, depth: Depth) -> String {
    match depth {
        Depth::TrueColor => alloc::format!("38;2;{};{};{}", colour.r, colour.g, colour.b),
        Depth::Ansi256 => alloc::format!("38;5;{}", xterm256(colour)),
        Depth::Ansi16 => {
            let index = ansi16(colour);
            if index >= 8 {
                alloc::format!("{}", 90 + index - 8)
            } else {
                alloc::format!("{}", 30 + index)
            }
        }
    }
}

/// Render the `LS_COLORS` value for our `ls`.
///
/// The mapping is semantic: directories are `path`, executables `success`, symlinks `info`,
/// broken links `error`, archives `warning`. No foreign tool is involved.
#[must_use]
pub fn ls_colors(palette: &Palette, depth: Depth) -> String {
    let role = |role| params(palette.get(role), depth);
    alloc::format!(
        "di={}:ln={}:ex={}:fi={}:or={}:mi={}:*.tar={}:*.gz={}",
        role(Role::Path),
        role(Role::Info),
        role(Role::Success),
        role(Role::Muted),
        role(Role::Error),
        role(Role::Error),
        role(Role::Warning),
        role(Role::Warning),
    )
}

/// Render a POSIX shell fragment for `LESS_TERMCAP_*`.
#[must_use]
pub fn less_termcap(palette: &Palette, depth: Depth) -> String {
    let bold = params(palette.get(Role::Accent), depth);
    let soft = params(palette.get(Role::Info), depth);
    let underline = params(palette.get(Role::Path), depth);
    let reset = "0".to_string();
    alloc::format!(
        "export LESS_TERMCAP_md=$'\\033[{}m'\n\
         export LESS_TERMCAP_me=$'\\033[{}m'\n\
         export LESS_TERMCAP_so=$'\\033[{}m'\n\
         export LESS_TERMCAP_se=$'\\033[{}m'\n\
         export LESS_TERMCAP_us=$'\\033[{}m'\n\
         export LESS_TERMCAP_ue=$'\\033[{}m'\n",
        bold,
        reset,
        soft,
        reset,
        underline,
        reset
    )
}

/// The complete shell fragment written by `raven theme apply`.
#[must_use]
pub fn shell_fragment(palette: &Palette, depth: Depth) -> String {
    alloc::format!(
        "# generated by raven theme apply; do not edit\n\
         export LS_COLORS='{}'\n{}",
        ls_colors(palette, depth),
        less_termcap(palette, depth)
    )
}

