//! Scheme server loop, request dispatch and deferred replies.

use alloc::sync::Arc;
use alloc::vec::Vec;
use core::time::Duration;

use raven_abi::errno::Errno;
use raven_abi::types::Handle;
use raven_ipc::protocol::{self, MAX_TRANSFER, Opcode, PACKET_SIZE, SchemePacket};
use raven_proto_fs::{OpenFlags, Stat};

use crate::kernel::{Kernel, RtKernel};
use crate::sync::SpinLock;

/// A handler failure or a deferred reply.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum HandlerError {
    /// Complete the request with this errno.
    Errno(Errno),
    /// Keep the request open and complete it later with [`Completer::complete`].
    Defer(u64),
}

impl From<Errno> for HandlerError {
    fn from(error: Errno) -> Self {
        Self::Errno(error)
    }
}

/// The result type of every [`Handler`] method.
pub type HandlerResult<T> = Result<T, HandlerError>;

/// A request received by [`Server::poll`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Packet {
    /// Server-side request handle used by `SEND`.
    pub handle: Handle,
    /// Decoded S11 packet.
    pub packet: SchemePacket,
}

/// The result of [`Handler::open`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Opened {
    /// A server-chosen file id, returned as the response cookie.
    File(u64),
    /// A handle to attach to the response (`REPLY_HANDLE`, S25).
    Attach(Handle),
}

/// Per-request context passed to the handler.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Ctx {
    /// Server-side request handle.
    pub request: Handle,
    /// Convenience token generated by the server; a handler may return it in
    /// [`HandlerError::Defer`].
    pub token: u64,
    /// Captured request buffer length (zero when absent).
    pub buffer_len: u64,
    /// Captured response buffer length (zero when absent).
    pub response_len: u64,
}

/// A scheme server handler.
///
/// Every method defaults to `-ENOSYS`. Return `Err(HandlerError::Defer(token))` from any method to
/// keep the request open; the same token is later passed to [`Completer::complete`]. Tokens must
/// be unique among the requests currently deferred by one server.
pub trait Handler {
    /// Open `path` (relative to the server root) with raw S11 wire flags.
    ///
    /// This is the pre-K66 entry point kept for servers that still interpret the
    /// legacy `READ`/`WRITE`/`CREATE` bits themselves.  New servers override
    /// [`Handler::open_with`] instead; the default implementation validates the
    /// wire flags and forwards the raw bits here.
    fn open(&mut self, path: &str, flags: u32, mode: u32, ctx: &Ctx) -> HandlerResult<Opened> {
        let _ = (path, flags, mode, ctx);
        Err(Errno::ENOSYS.into())
    }

    /// Open `path` with validated K66 open flags and the create mode.
    ///
    /// `mode` is the create mode (`0o644` for protocol version 1) when
    /// `flags.create()` is set; it is zero otherwise.  A server that does not
    /// need the typed interface may leave the default, which forwards the raw
    /// wire bits to [`Handler::open`].
    fn open_with(
        &mut self,
        path: &str,
        flags: OpenFlags,
        mode: u32,
        ctx: &Ctx,
    ) -> HandlerResult<Opened> {
        self.open(path, u32::from(flags.to_wire()), mode, ctx)
    }

    /// Read from `file` at `offset` into `buffer`.
    fn read(&mut self, file: u64, offset: u64, buffer: &mut [u8]) -> HandlerResult<usize> {
        let _ = (file, offset, buffer);
        Err(Errno::ENOSYS.into())
    }

    /// Write `buffer` to `file` at `offset`.
    fn write(&mut self, file: u64, offset: u64, buffer: &[u8]) -> HandlerResult<usize> {
        let _ = (file, offset, buffer);
        Err(Errno::ENOSYS.into())
    }

    /// Close `file`.
    fn close(&mut self, file: u64) -> HandlerResult<()> {
        let _ = file;
        Err(Errno::ENOSYS.into())
    }

    /// Duplicate `file`, returning the new server file id.
    fn dup(&mut self, file: u64) -> HandlerResult<u64> {
        let _ = file;
        Err(Errno::ENOSYS.into())
    }

    /// Stat `file`.
    fn fstat(&mut self, file: u64) -> HandlerResult<Stat> {
        let _ = file;
        Err(Errno::ENOSYS.into())
    }

    /// Typed `CALL` on `file`; `request` and `response` are captured client buffers.
    fn call(&mut self, file: u64, request: &[u8], response: &mut [u8]) -> HandlerResult<usize> {
        let _ = (file, request, response);
        Err(Errno::ENOSYS.into())
    }
}

struct Deferred {
    token: u64,
    request: Handle,
    packet: SchemePacket,
}

/// A running scheme server.
pub struct Server<K: Kernel = RtKernel> {
    kernel: K,
    deferred: Arc<SpinLock<Vec<Deferred>>>,
    next_token: u64,
}

impl Server<RtKernel> {
    /// Register `name` using the real syscall implementation.
    pub fn register(name: &str) -> Result<Self, Errno> {
        Self::register_with(RtKernel, name)
    }
}

impl<K: Kernel> Server<K> {
    /// Register `name` with a caller-provided kernel implementation.
    pub fn register_with(kernel: K, name: &str) -> Result<Self, Errno> {
        kernel.scheme_register(name)?;
        Ok(Self {
            kernel,
            deferred: Arc::new(SpinLock::new(Vec::new())),
            next_token: 1,
        })
    }

    /// A cloneable handle for completing deferred replies.
    pub fn completer(&self) -> Completer<K> {
        Completer {
            kernel: self.kernel.clone(),
            deferred: Arc::clone(&self.deferred),
        }
    }

    /// Receive one request, waiting at most `timeout`.
    ///
    /// The real S11 `RECV` has no timeout and blocks until a request arrives; see
    /// [`Kernel::recv_timeout`]. Fake kernels used by host tests honor the timeout.
    pub fn poll(&mut self, timeout: Option<Duration>) -> Option<Packet> {
        let mut bytes = [0u8; PACKET_SIZE];
        let millis = timeout
            .map(|duration| u64::try_from(duration.as_millis()).unwrap_or(u64::MAX))
            .unwrap_or(u64::MAX);
        let handle = self
            .kernel
            .recv_timeout(&mut bytes, millis)
            .ok()
            .flatten()?;
        let packet = protocol::decode(&bytes).ok()?;
        if packet.validate(false).is_err() {
            return None;
        }
        Some(Packet { handle, packet })
    }

    /// Run forever, dispatching requests to `handler`.
    pub fn run(&mut self, handler: &mut dyn Handler) -> ! {
        loop {
            if let Some(packet) = self.poll(None) {
                let _ = self.dispatch(packet, handler);
            }
        }
    }

    /// Dispatch one request and send its response.
    pub fn dispatch(&mut self, packet: Packet, handler: &mut dyn Handler) -> Result<(), Errno> {
        let token = self.next_token;
        self.next_token = self.next_token.wrapping_add(1);
        let ctx = Ctx {
            request: packet.handle,
            token,
            buffer_len: packet.packet.buffer_len,
            response_len: packet.packet.response_len,
        };
        match self.handle(packet.packet, handler, &ctx) {
            Ok(()) => Ok(()),
            Err(HandlerError::Defer(token)) => {
                self.deferred.lock().push(Deferred {
                    token,
                    request: packet.handle,
                    packet: packet.packet,
                });
                Ok(())
            }
            Err(HandlerError::Errno(error)) => self.send_error(packet.handle, packet.packet, error),
        }
    }

    fn handle(
        &self,
        request: SchemePacket,
        handler: &mut dyn Handler,
        ctx: &Ctx,
    ) -> HandlerResult<()> {
        let opcode =
            Opcode::from_u16(request.opcode).ok_or_else(|| HandlerError::from(Errno::EPROTO))?;
        match opcode {
            Opcode::Open => {
                let path = core::str::from_utf8(request.path_bytes())
                    .map_err(|_| HandlerError::from(Errno::EINVAL))?;
                let flags = OpenFlags::from_wire(request.flags)
                    .map_err(|_| HandlerError::from(Errno::EINVAL))?;
                let mode = flags.create_mode().unwrap_or(0);
                match handler.open_with(path, flags, mode, ctx)? {
                    Opened::File(id) => self
                        .send_response(ctx.request, request, Ok(()), Some(id), 0, None)
                        .map_err(HandlerError::from),
                    Opened::Attach(handle) => {
                        self.kernel
                            .reply_attach(ctx.request, handle)
                            .map_err(HandlerError::from)?;
                        self.send_response(ctx.request, request, Ok(()), Some(0), 0, None)
                            .map_err(HandlerError::from)
                    }
                }
            }
            Opcode::Read => {
                let mut empty = [];
                let buffer = if request.buffer_len == 0 {
                    &mut empty[..]
                } else {
                    request_buffer_mut(&request)?
                };
                let written = handler.read(request.file_id, request.offset, buffer)?;
                if written > buffer.len() {
                    return Err(Errno::EPROTO.into());
                }
                self.send_response(ctx.request, request, Ok(()), None, written, None)
                    .map_err(HandlerError::from)
            }
            Opcode::Write => {
                let buffer = if request.buffer_len == 0 {
                    &[][..]
                } else {
                    request_buffer(&request)?
                };
                let written = handler.write(request.file_id, request.offset, buffer)?;
                if written > buffer.len() {
                    return Err(Errno::EPROTO.into());
                }
                self.send_response(ctx.request, request, Ok(()), None, written, None)
                    .map_err(HandlerError::from)
            }
            Opcode::Close => {
                handler.close(request.file_id)?;
                self.send_response(ctx.request, request, Ok(()), None, 0, None)
                    .map_err(HandlerError::from)
            }
            Opcode::Dup => {
                let id = handler.dup(request.file_id)?;
                self.send_response(ctx.request, request, Ok(()), Some(id), 0, None)
                    .map_err(HandlerError::from)
            }
            Opcode::Fstat => {
                let stat = handler.fstat(request.file_id)?;
                let mut data = [0u8; 64];
                stat.encode(&mut data)
                    .map_err(|_| HandlerError::from(Errno::EPROTO))?;
                self.send_response(ctx.request, request, Ok(()), None, 0, Some(data))
                    .map_err(HandlerError::from)
            }
            Opcode::Call => {
                let request_bytes = if request.buffer_len == 0 {
                    &[][..]
                } else {
                    request_buffer(&request)?
                };
                let mut empty = [];
                let response_bytes = if request.response_len == 0 {
                    &mut empty[..]
                } else {
                    response_buffer_mut(&request)?
                };
                let written = handler.call(request.file_id, request_bytes, response_bytes)?;
                if written > response_bytes.len() {
                    return Err(Errno::EPROTO.into());
                }
                self.send_response(ctx.request, request, Ok(()), None, written, None)
                    .map_err(HandlerError::from)
            }
        }
    }

    fn send_error(
        &self,
        request_handle: Handle,
        request: SchemePacket,
        error: Errno,
    ) -> Result<(), Errno> {
        self.send_response(request_handle, request, Err(error), None, 0, None)
    }

    fn send_response(
        &self,
        request_handle: Handle,
        request: SchemePacket,
        result: Result<(), Errno>,
        server_cookie: Option<u64>,
        result_len: usize,
        data: Option<[u8; 64]>,
    ) -> Result<(), Errno> {
        let mut response = request;
        response.buffer_len = 0;
        response.data_len = 0;
        match result {
            Ok(()) => {
                response.status = 0;
                if let Some(cookie) = server_cookie {
                    response.server_cookie = cookie;
                }
                if let Some(data) = data {
                    response.data = data;
                    response.data_len = 64;
                } else {
                    response.buffer_len = u64::try_from(result_len).unwrap_or(u64::MAX);
                }
            }
            Err(error) => {
                response.status = i32::from(error.0);
            }
        }
        let mut bytes = [0u8; PACKET_SIZE];
        protocol::encode(&response, &mut bytes).map_err(|_| Errno::EPROTO)?;
        self.kernel.send(request_handle, &bytes)
    }
}

/// A cloneable completion handle for deferred requests.
pub struct Completer<K: Kernel = RtKernel> {
    kernel: K,
    deferred: Arc<SpinLock<Vec<Deferred>>>,
}

impl<K: Kernel> Clone for Completer<K> {
    fn clone(&self) -> Self {
        Self {
            kernel: self.kernel.clone(),
            deferred: Arc::clone(&self.deferred),
        }
    }
}

impl<K: Kernel> Completer<K> {
    /// Complete a deferred request with a result length or an error.
    pub fn complete(&self, token: u64, result: Result<usize, Errno>) -> Result<(), Errno> {
        let deferred = {
            let mut table = self.deferred.lock();
            let index = table
                .iter()
                .position(|item| item.token == token)
                .ok_or(Errno::EINVAL)?;
            table.remove(index)
        };
        let mut response = deferred.packet;
        response.buffer_len = 0;
        response.data_len = 0;
        match result {
            Ok(length) => {
                response.status = 0;
                response.buffer_len = u64::try_from(length).unwrap_or(u64::MAX);
            }
            Err(error) => response.status = i32::from(error.0),
        }
        let mut bytes = [0u8; PACKET_SIZE];
        protocol::encode(&response, &mut bytes).map_err(|_| Errno::EPROTO)?;
        self.kernel.send(deferred.request, &bytes)
    }
}

fn checked_buffer(addr: u64, len: u64) -> Result<*mut u8, Errno> {
    if len == 0 {
        return Err(Errno::EINVAL);
    }
    if len > MAX_TRANSFER || addr == 0 {
        return Err(Errno::EFAULT);
    }
    usize::try_from(addr)
        .map(|value| value as *mut u8)
        .map_err(|_| Errno::EFAULT)
}

fn request_buffer(request: &SchemePacket) -> Result<&[u8], Errno> {
    let pointer = checked_buffer(request.buffer_addr, request.buffer_len)?;
    let length = usize::try_from(request.buffer_len).map_err(|_| Errno::EFAULT)?;
    // SAFETY: the S11 kernel maps exactly `buffer_len` bytes of the client buffer at
    // `buffer_addr` in this server's address space for the lifetime of the request. The length
    // is bounded by MAX_TRANSFER and the pointer is non-null.
    Ok(unsafe { core::slice::from_raw_parts(pointer, length) })
}

#[allow(clippy::mut_from_ref)] // the mutable slice is the S11 capture, not the immutable packet.
fn request_buffer_mut(request: &SchemePacket) -> Result<&mut [u8], Errno> {
    let pointer = checked_buffer(request.buffer_addr, request.buffer_len)?;
    let length = usize::try_from(request.buffer_len).map_err(|_| Errno::EFAULT)?;
    // SAFETY: the capture is writable for READ (the kernel created it with `writable = true`) and
    // is exclusively owned by this request in the server's address space.
    Ok(unsafe { core::slice::from_raw_parts_mut(pointer, length) })
}

#[allow(clippy::mut_from_ref)] // the mutable slice is the S11 response capture, not the packet.
fn response_buffer_mut(request: &SchemePacket) -> Result<&mut [u8], Errno> {
    let pointer = checked_buffer(request.response_addr, request.response_len)?;
    let length = usize::try_from(request.response_len).map_err(|_| Errno::EFAULT)?;
    // SAFETY: the second S11 capture is writable for CALL responses and is exclusively owned by
    // this request in the server's address space.
    Ok(unsafe { core::slice::from_raw_parts_mut(pointer, length) })
}
