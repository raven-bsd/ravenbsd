//! Linux userspace ABI data for the RavenBSD Linux personality.
//!
//! The crate is `no_std`, has no runtime dependencies and contains only plain data: syscall
//! numbers per architecture, errno values, UAPI flags and `#[repr(C)]` struct layouts.
//!
//! All values and layouts are derived from `linux-raw-sys` 0.12.1 (Apache-2.0 OR MIT), which
//! generates them from the Linux UAPI headers. Nothing here is copied from the Linux kernel
//! sources or from memory. The syscall tables are generated by
//! `cargo run -p raven-linux-abi --example gen_tables`; see `README.md`.

#![no_std]
#![forbid(unsafe_code)]
#![allow(missing_docs)] // Linux UAPI names are their own documentation; item docs explain the unusual parts.

pub mod errno;
pub mod flags;
pub mod structs;
pub mod sysnums;

/// A 64-bit architecture with a supported Linux syscall table and struct layout.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Hash)]
pub enum Arch {
    /// x86-64 (`x86_64`).
    X86_64,
    /// AArch64 (`aarch64`), using the asm-generic syscall table and layout.
    Aarch64,
    /// RISC-V 64 (`riscv64`), using the asm-generic syscall table and layout.
    Riscv64,
}

impl Arch {
    /// Every supported architecture.
    pub const ALL: [Arch; 3] = [Arch::X86_64, Arch::Aarch64, Arch::Riscv64];

    /// The architecture name as used in the generated tables and by `uname -m` conventions.
    pub const fn name(self) -> &'static str {
        match self {
            Arch::X86_64 => "x86_64",
            Arch::Aarch64 => "aarch64",
            Arch::Riscv64 => "riscv64",
        }
    }
}
