fn test_name(case: &str) -> String {
    let mut name = String::with_capacity(case.len() + 7);
    name.push_str("vector_");
    for ch in case.chars() {
        if ch.is_ascii_alphanumeric() {
            name.push(ch);
        } else {
            name.push('_');
        }
    }
    name
}

fn main() {
    let manifest = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let spec = Path::new(&manifest).join("../../spec/tcpip/vectors/headers.toml");
    println!("cargo:rerun-if-changed={}", spec.display());

    if let Ok(text) = fs::read_to_string(&spec) {
        for case in EXPECTED_CASES {
            if !text.contains(&format!("name = \"{case}\"")) {
                // Still generate the test: it will fail with a clear message at run time.
                println!("cargo:warning=header vector `{case}` is missing from headers.toml");
            }
        }
    }

    let mut generated = String::from(
        "// SPDX-License-Identifier: BSD-3-Clause\n\
         // Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors\n\
         // Generated by build.rs: one test per pinned header vector.\n\n",
    );
    generated.push_str("/// Case names pinned by the C02 contract.\n");
    generated.push_str("pub const GENERATED_CASE_NAMES: &[&str] = &[\n");
    for case in EXPECTED_CASES {
        generated.push_str("    ");
        generated.push_str(&format!("{case:?}"));
        generated.push_str(",\n");
    }
    generated.push_str("];\n\n");
    for case in EXPECTED_CASES {
        generated.push_str("#[test]\nfn ");
        generated.push_str(&test_name(case));
        generated.push_str("() { run_case(");
        generated.push_str(&format!("{case:?}"));
        generated.push_str("); }\n\n");
    }

    let out_dir = env::var("OUT_DIR").expect("OUT_DIR");
    fs::write(Path::new(&out_dir).join("vector_cases.rs"), generated)
        .expect("write generated vector tests");
}
