//! First-party 8x16 ASCII font for the HDMI text console.
//!
//! The glyph bitmap is the same public-domain `bold8x16` table already used by the E1d E-Ink
//! service. It is transpiled literally from NetBSD `sys/dev/wsfont/bold8x16.h`
//! (`$NetBSD: bold8x16.h,v 1.13 2008/04/28 20:24:01 martin Exp $`): the font data is explicitly
//! public domain and the containing file carries the NetBSD Foundation 2-clause BSD notice. We
//! keep the donor provenance here and in `docs/hdmi-console.md`; no other donor code is copied.
//!
//! Each glyph is 8 pixels wide and 16 rows high, MSB first (`0x80` is the leftmost pixel), for the
//! printable ASCII range `0x20..=0x7e`. Bytes outside that range use the `?` replacement.

/// Width of one font cell in pixels.
pub const FONT_WIDTH: usize = 8;
/// Height of one font cell in pixels.
pub const FONT_HEIGHT: usize = 16;
/// First printable ASCII byte.
pub const FIRST_ASCII: u8 = 0x20;
/// Last printable ASCII byte.
pub const LAST_ASCII: u8 = 0x7e;
/// Replacement character for non-printable/non-ASCII bytes.
pub const REPLACEMENT: u8 = b'?';

/// One monochrome glyph: row bytes, MSB first.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Glyph {
    /// Cell width in pixels.
    pub width: u8,
    /// Cell height in pixels.
    pub height: u8,
    /// Row-major bitmap; the first byte is the top row.
    pub data: &'static [u8],
}

/// The glyph for `character`, with the `?` replacement outside printable ASCII.
#[must_use]
pub fn glyph(character: u8) -> Glyph {
    let index = if (FIRST_ASCII..=LAST_ASCII).contains(&character) {
        usize::from(character - FIRST_ASCII)
    } else {
        usize::from(REPLACEMENT - FIRST_ASCII)
    };
    Glyph {
        width: FONT_WIDTH as u8,
        height: FONT_HEIGHT as u8,
        data: ASCII_GLYPHS.get(index).map_or(&BLANK, |glyph| glyph),
    }
}

const BLANK: [u8; FONT_HEIGHT] = [0; FONT_HEIGHT];

