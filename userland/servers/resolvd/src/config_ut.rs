//! `resolv.conf` parser tests.

use alloc::vec;

use super::*;

#[test]
fn parses_nameservers_and_ignores_other_lines() {
    let config = parse(
        "# comment\n\
         search test\n\
         nameserver 127.0.0.1\n\
         nameserver 192.0.2.53 # trailing\n\
         options timeout:1 attempts:2\n\
         nameserver 127.0.0.1\n\
         nameserver 300.1.1.1\n\
         nameserver 198.51.100.1 extra\n",
    );
    assert_eq!(config.servers, vec![[127, 0, 0, 1], [192, 0, 2, 53]]);
}

#[test]
fn renders_the_servers_in_order() {
    let config = Config {
        servers: vec![[10, 0, 2, 3], [10, 0, 2, 4]],
    };
    assert_eq!(
        config.render(),
        "# Generated by resolvd.\nnameserver 10.0.2.3\nnameserver 10.0.2.4\n"
    );
}

#[test]
fn ignores_malformed_addresses() {
    assert!(
        parse("nameserver\nnameserver .\nnameserver 1.2.3\nnameserver 1.2.3.4.5")
            .servers
            .is_empty()
    );
}
