//! `resolv.conf` parser tests.

use alloc::vec;

use super::*;

#[test]
fn parses_nameservers_and_ignores_other_lines() {
    let config = parse(
        "# comment\n\
         search test\n\
         nameserver 127.0.0.1\n\
         nameserver 192.0.2.53 # trailing\n\
         options timeout:1 attempts:2\n\
         nameserver 127.0.0.1\n\
         nameserver 300.1.1.1\n\
         nameserver 198.51.100.1 extra\n",
    );
    assert_eq!(config.servers, vec![[127, 0, 0, 1], [192, 0, 2, 53]]);
}

#[test]
fn renders_the_servers_in_order() {
    let config = Config {
        servers: vec![[10, 0, 2, 3], [10, 0, 2, 4]],
    };
    assert_eq!(
        config.render(),
        "# Generated by resolvd.\nnameserver 10.0.2.3\nnameserver 10.0.2.4\n"
    );
}

#[test]
fn ignores_malformed_addresses() {
    assert!(
        parse("nameserver\nnameserver .\nnameserver 1.2.3\nnameserver 1.2.3.4.5")
            .servers
            .is_empty()
    );
}

#[test]
fn a_static_override_requires_a_nameserver() {
    assert!(has_static_override("nameserver 192.0.2.53\n"));
    assert!(!has_static_override("# comment only\n"));
    assert!(!has_static_override("nameserver 300.1.1.1\n"));
}

#[test]
fn generated_content_is_not_a_static_override() {
    let generated = Config {
        servers: vec![[10, 0, 2, 3]],
    }
    .render();
    assert!(is_generated(&generated));
    assert!(!has_static_override(&generated));
    assert!(has_static_override(&format!("# admin file\n{generated}")));
}
