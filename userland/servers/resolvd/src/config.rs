//! `/etc/resolv.conf` parsing and rendering.
//!
//! Only the directives the resolver uses are interpreted: `nameserver`, with
//! IPv4 addresses (the native stack exposes IPv4 servers).  Unknown lines and
//! comments are ignored; a malformed nameserver line is skipped rather than
//! guessed.

use alloc::format;
use alloc::string::String;
use alloc::vec::Vec;

/// Resolver configuration.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Config {
    /// Up to eight IPv4 nameservers, in file order.
    pub servers: Vec<[u8; 4]>,
}

impl Config {
    /// Render a file with one `nameserver` line per address.
    pub fn render(&self) -> String {
        let mut text = String::from("# Generated by resolvd.\n");
        for server in self.servers.iter().take(8) {
            text.push_str(&format!(
                "nameserver {}.{}.{}.{}\n",
                server[0], server[1], server[2], server[3]
            ));
        }
        text
    }
}

/// Parse a resolv.conf text.  At most eight servers are retained.
pub fn parse(text: &str) -> Config {
    let mut servers = Vec::new();
    for line in text.lines() {
        let line = line.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        let mut fields = line.split_whitespace();
        let Some(directive) = fields.next() else {
            continue;
        };
        if directive != "nameserver" {
            continue;
        }
        let Some(value) = fields.next() else {
            continue;
        };
        if fields.next().is_some() {
            continue;
        }
        if let Some(address) = parse_ipv4(value)
            && !servers.contains(&address)
            && servers.len() < 8
        {
            servers.push(address);
        }
    }
    Config { servers }
}

fn parse_ipv4(text: &str) -> Option<[u8; 4]> {
    let mut octets = [0u8; 4];
    let mut count = 0usize;
    for part in text.split('.') {
        if count == 4 || part.is_empty() || part.len() > 3 {
            return None;
        }
        if !part.bytes().all(|byte| byte.is_ascii_digit()) {
            return None;
        }
        let value: u16 = part.parse().ok()?;
        if value > 255 {
            return None;
        }
        octets[count] = value as u8;
        count += 1;
    }
    (count == 4).then_some(octets)
}

