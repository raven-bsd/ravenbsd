//! Deterministic management `posix/GAPS.md` rendering and the stale-file check.

use std::collections::BTreeMap;
use std::fmt::Write;
use std::path::Path;

use anyhow::{Context, Result, bail};

use crate::model::{Profile, Status, TraceFile, read_symbols};

fn status_name(status: Status) -> &'static str {
    status.as_str()
}

#[allow(clippy::too_many_arguments)] // one argument per rendered table column
fn row(
    output: &mut String,
    area: &str,
    id: &str,
    name: &str,
    status: Status,
    owner: &str,
    evidence: &str,
    extra: &str,
    waiver: &str,
) {
    let evidence = if evidence.is_empty() {
        "none"
    } else {
        evidence
    };
    let extra = if waiver.trim().is_empty() {
        extra.to_string()
    } else if extra.is_empty() {
        format!("waiver: {waiver}")
    } else {
        format!("{extra}; waiver: {waiver}")
    };
    let _ = writeln!(
        output,
        "| `{}` | `{}` | {} | {} | `{}` | {} |",
        id,
        name,
        status_name(status),
        owner,
        evidence,
        extra
    );
    let _ = area;
}

fn write_table(output: &mut String, title: &str, headers: &str, rows: impl FnOnce(&mut String)) {
    let _ = writeln!(output, "\n## {title}\n");
    let _ = writeln!(output, "| {headers} |");
    let _ = writeln!(output, "|---|---|---|---|---|---|");
    rows(output);
}

/// Render the complete generated gap matrix.
pub fn render_gaps(root: &Path, profile: &Profile, trace: &TraceFile) -> Result<String> {
    let mut output = String::new();
    let _ = writeln!(output, "<!-- SPDX-License-Identifier: BSD-3-Clause -->");
    let _ = writeln!(
        output,
        "<!-- Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors -->"
    );
    let _ = writeln!(
        output,
        "<!-- GENERATED by tools/posix-conform; edit profile.toml or seed.rs, not this file. -->"
    );
    let _ = writeln!(output, "\n# POSIX.1-2024 gap matrix\n");
    let _ = writeln!(
        output,
        "Profile `{}`, schema {}. Status values are `missing`, `partial`, `present` and `waived`; \
         `evidence` is a file or test name and never standard prose.",
        profile.standard, profile.schema
    );
    let _ = writeln!(
        output,
        "Platform gate: x86_64 `{}`; aarch64 `{}`; riscv64 `{}`.",
        profile.platform.x86_64, profile.platform.aarch64, profile.platform.riscv64
    );

    let counts = profile.counts();
    let _ = writeln!(output, "\n## Summary\n");
    let _ = writeln!(
        output,
        "| area | total | missing | partial | present | waived |"
    );
    let _ = writeln!(output, "|---|---:|---:|---:|---:|---:|");
    let mut total = [0usize; 4];
    for (area, values) in &counts {
        let sum: usize = values.iter().sum();
        for (index, value) in values.iter().enumerate() {
            total[index] += value;
        }
        let _ = writeln!(
            output,
            "| {area} | {sum} | {} | {} | {} | {} |",
            values[0], values[1], values[2], values[3]
        );
    }
    let grand: usize = total.iter().sum();
    let _ = writeln!(
        output,
        "| **all** | **{grand}** | **{}** | **{}** | **{}** | **{}** |",
        total[0], total[1], total[2], total[3]
    );
    let trace_ids = trace.trace.len();
    let _ = writeln!(
        output,
        "\nTraceability rows: {trace_ids}; profile rows: {grand}."
    );

    write_table(
        &mut output,
        "Headers",
        "id | header | status | owner | evidence | note",
        |out| {
            for entry in &profile.header {
                row(
                    out,
                    "header",
                    &entry.meta.id,
                    &entry.name,
                    entry.meta.status,
                    &entry.meta.owner,
                    &entry.meta.evidence,
                    if entry.meta.pg.is_empty() {
                        ""
                    } else {
                        "PG linked"
                    },
                    &entry.meta.waiver,
                );
            }
        },
    );
    write_table(
        &mut output,
        "Interfaces",
        "id | interface | status | owner | evidence | header",
        |out| {
            for entry in &profile.interface {
                row(
                    out,
                    "interface",
                    &entry.meta.id,
                    &entry.name,
                    entry.meta.status,
                    &entry.meta.owner,
                    &entry.meta.evidence,
                    &entry.header,
                    &entry.meta.waiver,
                );
            }
        },
    );
    write_table(
        &mut output,
        "Utilities",
        "id | utility | status | owner | evidence | test",
        |out| {
            for entry in &profile.utility {
                row(
                    out,
                    "utility",
                    &entry.meta.id,
                    &entry.name,
                    entry.meta.status,
                    &entry.meta.owner,
                    &entry.meta.evidence,
                    &entry.test,
                    &entry.meta.waiver,
                );
            }
        },
    );
    write_table(
        &mut output,
        "Shell features",
        "id | feature | status | owner | evidence | note",
        |out| {
            for entry in &profile.shell_feature {
                row(
                    out,
                    "shell",
                    &entry.meta.id,
                    &entry.name,
                    entry.meta.status,
                    &entry.meta.owner,
                    &entry.meta.evidence,
                    &entry.description,
                    &entry.meta.waiver,
                );
            }
        },
    );
    write_table(
        &mut output,
        "Filesystem behaviour",
        "id | behaviour | status | owner | evidence | pg",
        |out| {
            for entry in &profile.filesystem {
                row(
                    out,
                    "filesystem",
                    &entry.meta.id,
                    &entry.name,
                    entry.meta.status,
                    &entry.meta.owner,
                    &entry.meta.evidence,
                    &entry.meta.pg.join(", "),
                    &entry.meta.waiver,
                );
            }
        },
    );
    write_table(
        &mut output,
        "Process behaviour",
        "id | behaviour | status | owner | evidence | pg",
        |out| {
            for entry in &profile.process {
                row(
                    out,
                    "process",
                    &entry.meta.id,
                    &entry.name,
                    entry.meta.status,
                    &entry.meta.owner,
                    &entry.meta.evidence,
                    &entry.meta.pg.join(", "),
                    &entry.meta.waiver,
                );
            }
        },
    );
    write_table(
        &mut output,
        "TTY behaviour",
        "id | behaviour | status | owner | evidence | pg",
        |out| {
            for entry in &profile.tty {
                row(
                    out,
                    "tty",
                    &entry.meta.id,
                    &entry.name,
                    entry.meta.status,
                    &entry.meta.owner,
                    &entry.meta.evidence,
                    &entry.meta.pg.join(", "),
                    &entry.meta.waiver,
                );
            }
        },
    );

    // PG roll-up, useful for the P2/P3/P5 ticket split.
    let mut by_pg: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for (_, meta) in profile.metas() {
        for pg in &meta.pg {
            by_pg.entry(pg.clone()).or_default().push(meta.id.clone());
        }
    }
    let _ = writeln!(output, "\n## Platform-gap roll-up\n");
    let _ = writeln!(output, "| pg | requirement ids |");
    let _ = writeln!(output, "|---|---|");
    for (pg, mut ids) in by_pg {
        ids.sort();
        let _ = writeln!(output, "| `{pg}` | {} |", ids.join(", "));
    }

    // Current-tree facts. These are informational and are checked by validate().
    let symbols = read_symbols(root).unwrap_or_default();
    let mut utilities = Vec::new();
    if let Ok(entries) = std::fs::read_dir(root.join("userland/bin")) {
        for entry in entries.flatten() {
            if entry.path().is_dir()
                && let Some(name) = entry.file_name().to_str()
            {
                utilities.push(name.to_string());
            }
        }
    }
    utilities.sort();
    let _ = writeln!(output, "\n## Current tree\n");
    let _ = writeln!(output, "- frozen exported symbols: {}", symbols.len());
    let _ = writeln!(output, "- `userland/bin` directories: {}", utilities.len());
    let _ = writeln!(
        output,
        "- headers under `libc/ravenlibc/include`: {}",
        count_files(&root.join("libc/ravenlibc/include"))
    );
    let _ = writeln!(output, "- utility directories: {}", utilities.join(", "));

    let _ = writeln!(output, "\n## Top gaps\n");
    let mut gaps: Vec<(&str, &str, &str)> = Vec::new();
    for entry in &profile.header {
        if entry.meta.status != Status::Present {
            gaps.push(("header", &entry.name, entry.meta.evidence.as_str()));
        }
    }
    for entry in &profile.interface {
        if entry.meta.status != Status::Present {
            gaps.push(("interface", &entry.name, entry.meta.evidence.as_str()));
        }
    }
    for entry in &profile.utility {
        if entry.meta.status != Status::Present {
            gaps.push(("utility", &entry.name, entry.meta.evidence.as_str()));
        }
    }
    for entry in &profile.shell_feature {
        if entry.meta.status != Status::Present {
            gaps.push(("shell", &entry.name, entry.meta.evidence.as_str()));
        }
    }
    for entry in &profile.filesystem {
        if entry.meta.status != Status::Present {
            gaps.push(("filesystem", &entry.name, entry.meta.evidence.as_str()));
        }
    }
    for entry in &profile.process {
        if entry.meta.status != Status::Present {
            gaps.push(("process", &entry.name, entry.meta.evidence.as_str()));
        }
    }
    for entry in &profile.tty {
        if entry.meta.status != Status::Present {
            gaps.push(("tty", &entry.name, entry.meta.evidence.as_str()));
        }
    }
    gaps.sort_by(|left, right| (left.0, left.1).cmp(&(right.0, right.1)));
    let _ = writeln!(output, "| area | name | evidence |");
    let _ = writeln!(output, "|---|---|---|");
    for (area, name, evidence) in gaps.iter().take(80) {
        let _ = writeln!(output, "| {area} | `{name}` | `{evidence}` |");
    }
    let _ = writeln!(
        output,
        "\n{} gap rows are listed in full in the tables above; this short table is a review aid.",
        gaps.len()
    );
    Ok(output)
}

fn count_files(root: &Path) -> usize {
    let mut count = 0usize;
    let mut stack = vec![root.to_path_buf()];
    while let Some(dir) = stack.pop() {
        let Ok(entries) = std::fs::read_dir(&dir) else {
            continue;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                stack.push(path);
            } else if path.is_file() {
                count += 1;
            }
        }
    }
    count
}

/// Write the generated GAPS.md.
pub fn generate(root: &Path, profile: &Profile, trace: &TraceFile) -> Result<()> {
    let dir = crate::mgmt::posix_dir(root)?;
    std::fs::create_dir_all(&dir).with_context(|| format!("cannot create {}", dir.display()))?;
    let text = render_gaps(root, profile, trace)?;
    std::fs::write(dir.join("GAPS.md"), text).context("cannot write GAPS.md")
}

/// Fail when GAPS.md is not exactly the generated text.
pub fn check_current(root: &Path, profile: &Profile, trace: &TraceFile) -> Result<()> {
    let path = crate::mgmt::posix_dir(root)?.join("GAPS.md");
    let current = std::fs::read_to_string(&path)
        .with_context(|| format!("cannot read {}", path.display()))?;
    let expected = render_gaps(root, profile, trace)?;
    if current != expected {
        bail!("{} is stale; run `cargo xtask posix-gaps`", path.display());
    }
    Ok(())
}
