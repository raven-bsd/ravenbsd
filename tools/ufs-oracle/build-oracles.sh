# usage: build-oracles.sh [--force]
#
# Builds the NetBSD UFS oracle tools into $UFS_ORACLE_DIR (default
# /tmp/opencode/ufs-oracle) from the read-only donor checkout.  makefs is
# built from usr.sbin/makefs + libnbcompat; only the FFS backend is compiled
# (the other backends are stubbed out, see README.md).  fsck_ffs is attempted
# and its blocker recorded; it is best effort.
#
# Environment:
#   NETBSD_DONOR    donor checkout (default /home/bo/work/ravenos-workspace/ravenbsd-resources/netbsd)
#   UFS_ORACLE_DIR  scratch and output directory (default /tmp/opencode/ufs-oracle)
#   CC, CFLAGS      host compiler and flags
set -eu

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
: "${NETBSD_DONOR:=/home/bo/work/ravenos-workspace/ravenbsd-resources/netbsd}"
: "${UFS_ORACLE_DIR:=/tmp/opencode/ufs-oracle}"
CC=${CC:-cc}
CFLAGS=${CFLAGS:--O2}

FORCE=no
case ${1:-} in
    --force) FORCE=yes ;;
    "") ;;
    *) echo "usage: build-oracles.sh [--force]" >&2; exit 2 ;;
esac

D=$NETBSD_DONOR
if [ ! -d "$D/sys/ufs/ffs" ]; then
    echo "build-oracles.sh: NetBSD donor not found at $D" >&2
    exit 1
fi

REV=unknown
if [ -f "$(dirname "$D")/donors.lock" ]; then
    REV=$(awk '$1 == "netbsd" { print $2; exit }' "$(dirname "$D")/donors.lock")
fi

mkdir -p "$UFS_ORACLE_DIR"
STAMP_FILE=$UFS_ORACLE_DIR/.donor-rev
if [ "$FORCE" = no ] && [ -x "$UFS_ORACLE_DIR/makefs" ] && \
   [ "$(cat "$STAMP_FILE" 2>/dev/null || true)" = "$REV" ]; then
    echo "build-oracles.sh: makefs already built for netbsd $REV"
    echo "build-oracles.sh: use --force to rebuild"
    exit 0
fi

START=$(date +%s)
S=$UFS_ORACLE_DIR/src
OBJ=$UFS_ORACLE_DIR/obj

echo "build-oracles.sh: building makefs from netbsd $REV"
rm -rf "$S" "$OBJ"
mkdir -p "$S/tools" "$OBJ"

cp -R "$D/tools/compat" "$S/tools/compat"
for d in sys lib common external include usr.sbin sbin; do
    ln -s "$D/$d" "$S/$d"
done

(
    cd "$S/tools/compat"
    mkdir -p include/sys include/machine include/rpc include/arpa
    rm -f nbtool_config.h defs.mk config.cache
    CC="$CC" CFLAGS="$CFLAGS" CPPFLAGS="-D_FILE_OFFSET_BITS=64" \
        ./configure
) > "$UFS_ORACLE_DIR/compat-configure.log" 2>&1 || {
    echo "build-oracles.sh: libnbcompat configure failed:" >&2
    tail -n 20 "$UFS_ORACLE_DIR/compat-configure.log" >&2
    exit 1
}

INCLUDES="-I $S/tools/compat -I $S/tools/compat/include
 -I $D/usr.sbin/makefs -I $D/usr.sbin/makefs/ffs
 -I $D/sys/fs/cd9660 -I $D/usr.sbin/mtree -I $D/sbin/mknod"

compile() { # compile <object-name> <source-path-relative-to-donor>
    if ! "$CC" $CFLAGS -c \
        -DHAVE_NBTOOL_CONFIG_H=1 -D_FILE_OFFSET_BITS=64 -DMAKEFS \
        $INCLUDES -o "$OBJ/$1.o" "$D/$2" 2> "$OBJ/$1.log"; then
        echo "build-oracles.sh: failed to compile $2" >&2
        sed -n '1,20p' "$OBJ/$1.log" >&2
        exit 1
    fi
}

# makefs front end and FFS back end.
compile makefs usr.sbin/makefs/makefs.c
compile walk usr.sbin/makefs/walk.c
compile ffs usr.sbin/makefs/ffs.c
compile ffs_alloc usr.sbin/makefs/ffs/ffs_alloc.c
compile ffs_balloc usr.sbin/makefs/ffs/ffs_balloc.c
compile mkfs usr.sbin/makefs/ffs/mkfs.c
compile ufs_bmap usr.sbin/makefs/ffs/ufs_bmap.c
compile buf usr.sbin/makefs/ffs/buf.c
compile ffs_bswap sys/ufs/ffs/ffs_bswap.c
compile ffs_subr sys/ufs/ffs/ffs_subr.c
compile ffs_tables sys/ufs/ffs/ffs_tables.c
compile getid usr.sbin/mtree/getid.c
compile misc usr.sbin/mtree/misc.c
compile spec usr.sbin/mtree/spec.c
compile pack_dev sbin/mknod/pack_dev.c

# libnbcompat pieces that makefs actually links.  The full libnbcompat has
# many more files; these are the ones referenced by the FFS-only build.
compile compat_efun lib/libutil/efun.c
compile compat_random common/lib/libc/stdlib/random.c
compile compat_strlcpy common/lib/libc/string/strlcpy.c
compile compat_strlcat common/lib/libc/string/strlcat.c
compile compat_strsuftoll lib/libc/stdlib/strsuftoll.c
compile compat_setprogname tools/compat/setprogname.c
compile compat_pwcache lib/libc/gen/pwcache.c
compile compat_getmode tools/compat/getmode.c
compile compat_unvis lib/libc/gen/unvis.c
compile compat_vis lib/libc/gen/vis.c
compile compat_stat_flags lib/libutil/stat_flags.c
compile compat_fparseln lib/libc/stdio/fparseln.c
compile compat_reallocarr lib/libc/stdlib/reallocarr.c
compile compat_strtoi common/lib/libc/stdlib/strtoi.c
compile compat_strtou common/lib/libc/stdlib/strtou.c
compile compat_fgetln tools/compat/fgetln.c
compile compat_setpassent tools/compat/setpassent.c
compile compat_setgroupent tools/compat/setgroupent.c

# makefs.c references every backend in its fstype table.  We only build FFS;
# these stubs keep the table linkable and fail cleanly for other -t values.
cat > "$UFS_ORACLE_DIR/ffs-only-stubs.c" <<'EOF'
/*
 * Generated by build-oracles.sh.  Not part of the RavenBSD source tree.
 * Stubs for the makefs backends that are not compiled into the FFS oracle.
 */
#include "makefs.h"
#define STUB(name) \
void name##_prep_opts(fsinfo_t *o) { (void)o; } \
int name##_parse_opts(const char *a, fsinfo_t *o) { (void)a; (void)o; return 0; } \
void name##_cleanup_opts(fsinfo_t *o) { (void)o; } \
void name##_makefs(const char *s, const char *d, fsnode *r, fsinfo_t *o) \
{ (void)s; (void)d; (void)r; (void)o; }
STUB(cd9660)
STUB(chfs)
STUB(v7fs)
STUB(msdos)
STUB(udf)
EOF
"$CC" $CFLAGS -c -DHAVE_NBTOOL_CONFIG_H=1 -D_FILE_OFFSET_BITS=64 \
    $INCLUDES -o "$OBJ/stubs.o" "$UFS_ORACLE_DIR/ffs-only-stubs.c" || {
    echo "build-oracles.sh: failed to compile the FFS-only stubs" >&2
    exit 1
}

"$CC" -o "$UFS_ORACLE_DIR/makefs" "$OBJ"/*.o -lz -lm || {
    echo "build-oracles.sh: link failed" >&2
    exit 1
}

if ! "$UFS_ORACLE_DIR/makefs" 2>&1 | grep -q '^Usage:'; then
    echo "build-oracles.sh: built binary does not print usage" >&2
    exit 1
fi
echo "build-oracles.sh: makefs: $UFS_ORACLE_DIR/makefs"

# fsck_ffs is a NetBSD target program, not a host tool.  Try the first file so
# the exact blocker is recorded; the full build is documented as BLOCKED.
mkdir -p "$UFS_ORACLE_DIR/nbinclude"
ln -sfn "$D/sys/ufs" "$UFS_ORACLE_DIR/nbinclude/ufs"
ln -sfn "$D/sys/fs" "$UFS_ORACLE_DIR/nbinclude/fs"
FSCK_INCLUDES="-I $UFS_ORACLE_DIR/nbinclude -I $S/tools/compat
 -I $S/tools/compat/include -I $D/sbin/fsck_ffs -I $D/sbin/fsck
 -I $D/sbin/dump -I $D/sys/ufs/ffs -I $D/sys/ufs/ufs -I $D/sys/kern
 -I $D/usr.sbin/mtree -I $D/sbin/mknod"
set +e
"$CC" $CFLAGS -c -DHAVE_NBTOOL_CONFIG_H=1 -D_FILE_OFFSET_BITS=64 \
    -DWAPBL_DEBUG_PRINT=0 \
    '-D__RCSID(x)=' '-D__COPYRIGHT(x)=' \
    '-D__unused=__attribute__((unused))' '-D__dead=__attribute__((noreturn))' \
    -include stdint.h $FSCK_INCLUDES \
    -o "$OBJ/fsck_main.o" "$D/sbin/fsck_ffs/main.c" \
    > "$UFS_ORACLE_DIR/fsck-ffs.log" 2>&1
FSCK_RC=$?
set -e
if [ "$FSCK_RC" -eq 0 ]; then
    echo "build-oracles.sh: fsck_ffs: main.c compiles, but the full fsck build is not implemented"
else
    echo "build-oracles.sh: fsck_ffs: NOT BUILT (first blocker in $UFS_ORACLE_DIR/fsck-ffs.log):"
    sed -n '1,3p' "$UFS_ORACLE_DIR/fsck-ffs.log" | sed 's/^/    /'
fi

printf '%s\n' "$REV" > "$STAMP_FILE"
END=$(date +%s)
echo "build-oracles.sh: done in $((END - START))s (makefs mandatory: yes; fsck_ffs: no)"
