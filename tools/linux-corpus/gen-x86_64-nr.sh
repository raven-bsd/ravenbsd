# usage: gen-x86_64-nr.sh <path-to-linux-raw-sys/src/x86_64/general.rs> [revision]
#
# Writes src/x86_64_nr.rs. The table is taken from the donor's generated Rust
# constants (lines `pub const __NR_name: u32 = N;`), never from Linux kernel
# source or memory. The donor revision is printed in the generated header.
set -eu

src=${1:?usage: gen-x86_64-nr.sh <general.rs> [revision]}
rev=${2:-3b15c17f2688445cd3e9ef2907113829837773dd}
out=$(dirname "$0")/src/x86_64_nr.rs

{
    printf '%s\n' \
        '// SPDX-License-Identifier: BSD-3-Clause' \
        '// Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors' \
        '' \
        '//! x86_64 Linux syscall numbers.' \
        '//!' \
        "//! @generated by \`tools/linux-corpus/gen-x86_64-nr.sh\` from" \
        "//! \`linux-raw-sys $rev src/x86_64/general.rs\` (Apache-2.0 OR MIT)." \
        '//! Do not edit by hand.'
    printf '\n'
    printf 'pub(crate) static X86_64_NR: &[(&str, u32)] = &[\n'
    grep '^pub const __NR_' "$src" |
        sed -E 's/^pub const __NR_([[:alnum:]_]+): u32 = ([0-9]+);$/\1 \2/' |
        LC_ALL=C sort |
        while read -r name number; do
            printf '    ("%s", %s),\n' "$name" "$number"
        done
    printf '];\n\n'
    printf '%s\n' \
        '/// Look up an x86_64 syscall number by name.' \
        'pub(crate) fn lookup(name: &str) -> Option<u32> {' \
        '    X86_64_NR' \
        '        .binary_search_by(|entry| entry.0.cmp(name))' \
        '        .ok()' \
        '        .map(|index| X86_64_NR[index].1)' \
        '}'
} > "$out"

printf 'wrote %s\n' "$out"
