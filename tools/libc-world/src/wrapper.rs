//! The generated compiler wrapper and CMake toolchain file (section 4.4).

use std::fs;
use std::path::Path;

use anyhow::{Context, Result};

use crate::model::triple;

/// Link mode of a generated wrapper.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum LinkMode {
    /// `libc.a` first.
    Static,
    /// `libc.so.1` through the loader.
    Dynamic,
}

impl LinkMode {
    /// Parse the CLI value.
    #[must_use]
    pub fn parse(value: &str) -> Option<Self> {
        match value {
            "static" => Some(Self::Static),
            "dynamic" => Some(Self::Dynamic),
            _ => None,
        }
    }

    /// The wire text.
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Static => "static",
            Self::Dynamic => "dynamic",
        }
    }
}

/// Render the `raven-cc` POSIX `sh` wrapper.
#[must_use]
pub fn wrapper_script(arch: &str, sysroot: &Path, link: LinkMode) -> String {
    let triple = triple(arch).unwrap_or_else(|| format!("{arch}-unknown-ravenbsd"));
    let sysroot = sysroot.display();
    let executable = match link {
        LinkMode::Static => "BUILTINS=\n\
             [ -f \"$SYSROOT/usr/lib/libclang_rt.builtins.a\" ] && BUILTINS=-lclang_rt.builtins\n\
             exec clang $COMMON -nostdlib -nostartfiles -static -Wl,--error-limit=0 -Wl,-z,max-page-size=4096 \\\n  \
             \"$SYSROOT/usr/lib/crt1.o\" \"$SYSROOT/usr/lib/crti.o\" \"$@\" -L\"$SYSROOT/usr/lib\" -lc $BUILTINS \"$SYSROOT/usr/lib/crtn.o\"\n"
            .to_string(),
        LinkMode::Dynamic => "exec clang $COMMON -nostdlib -nostartfiles -pie -Wl,-dynamic-linker,/libexec/ld-elf.so.1 -Wl,--error-limit=0 -Wl,-z,max-page-size=4096 \\\n  \"$SYSROOT/usr/lib/Scrt1.o\" \"$SYSROOT/usr/lib/crti.o\" \"$@\" -L\"$SYSROOT/lib\" -L\"$SYSROOT/usr/lib\" -lc \"$SYSROOT/usr/lib/crtn.o\"\n".to_string(),
    };
    format!(
        "#!/bin/sh\n\
         # GENERATED by libc-world; do not edit\n\
         set -eu\n\
         TRIPLE={triple}\n\
         SYSROOT={sysroot}\n\
         LOG=${{RAVEN_WORLD_LOG:-}}\n\
         COMMON=\"--target=$TRIPLE --sysroot=$SYSROOT -fuse-ld=lld -D__ravenbsd__=1 -D__unix__=1 -D__unix=1 -Werror=implicit-function-declaration -Werror=int-conversion -Wno-error=incompatible-pointer-types\"\n\
         mode=link; mflag=0; shared=0; partial=0\n\
         for a in \"$@\"; do\n\
         \x20\x20case $a in\n\
         \x20\x20\x20\x20-c|-S|-E) mode=compile ;;\n\
         \x20\x20\x20\x20-M|-MM) mode=compile; mflag=1 ;;\n\
         \x20\x20\x20\x20-MD|-MMD|-MF|-MT|-MQ) mflag=1 ;;\n\
         \x20\x20\x20\x20-shared) shared=1 ;;\n\
         \x20\x20\x20\x20-r|-Wl,-r) partial=1 ;;\n\
         \x20\x20esac\n\
         done\n\
         [ -n \"$LOG\" ] && mkdir -p \"$LOG\"\n\
         if [ \"$mode\" = compile ]; then\n\
         \x20\x20[ -n \"$LOG\" ] && echo \"compile $*\" >> \"$LOG/calls.log\"\n\
         \x20\x20if [ \"$mflag\" = 0 ] && [ -n \"$LOG\" ]; then\n\
         \x20\x20\x20\x20mkdir -p \"$LOG/deps\"\n\
         \x20\x20\x20\x20exec clang $COMMON \"$@\" -MD -MF \"$LOG/deps/$$.d\"\n\
         \x20\x20fi\n\
         \x20\x20exec clang $COMMON \"$@\"\n\
         fi\n\
         [ -n \"$LOG\" ] && echo \"link $*\" >> \"$LOG/calls.log\"\n\
         if [ \"$partial\" = 1 ]; then exec clang $COMMON -nostdlib \"$@\"; fi\n\
         if [ \"$shared\" = 1 ]; then exec clang $COMMON -nostdlib -nostartfiles -shared \"$@\" -L\"$SYSROOT/usr/lib\" -Wl,--error-limit=0 -Wl,-z,max-page-size=4096; fi\n\
         {executable}"
    )
}

/// Write the wrapper with mode 0755.
pub fn write_wrapper(path: &Path, arch: &str, sysroot: &Path, link: LinkMode) -> Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .with_context(|| format!("cannot create {}", parent.display()))?;
    }
    fs::write(path, wrapper_script(arch, sysroot, link))
        .with_context(|| format!("cannot write {}", path.display()))?;
    set_executable(path)?;
    Ok(())
}

fn set_executable(path: &Path) -> Result<()> {
    use std::os::unix::fs::PermissionsExt as _;
    let mut permissions = fs::metadata(path)?.permissions();
    permissions.set_mode(0o755);
    fs::set_permissions(path, permissions)?;
    Ok(())
}

/// Render the CMake toolchain file.
#[must_use]
pub fn toolchain_cmake(arch: &str, compiler: &Path, sysroot: &Path) -> String {
    let triple = triple(arch).unwrap_or_else(|| format!("{arch}-unknown-ravenbsd"));
    format!(
        "set(CMAKE_SYSTEM_NAME Generic)\n\
         set(CMAKE_SYSTEM_PROCESSOR {arch})\n\
         set(CMAKE_C_COMPILER {compiler})\n\
         set(CMAKE_C_COMPILER_TARGET {triple})\n\
         set(CMAKE_SYSROOT {sysroot})\n\
         set(CMAKE_TRY_COMPILE_TARGET_TYPE STATIC_LIBRARY)\n\
         set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)\n\
         set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)\n\
         set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)\n\
         set(UNIX 1)\n",
        compiler = compiler.display(),
        sysroot = sysroot.display(),
    )
}

/// Write the CMake toolchain file.
pub fn write_toolchain_cmake(
    path: &Path,
    arch: &str,
    compiler: &Path,
    sysroot: &Path,
) -> Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, toolchain_cmake(arch, compiler, sysroot))
        .with_context(|| format!("cannot write {}", path.display()))?;
    Ok(())
}

