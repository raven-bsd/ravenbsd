# usage: scripts/doctor.sh [--write-env]
# Reports which tools, firmware files, Rust toolchain parts are present. Exit 0 if everything REQUIRED is present.
# --write-env also writes .raven-env.mk (firmware paths for the Makefile; ignored by git).
set -eu
. "$(dirname "$0")/lib.sh"

WRITE=0; [ "${1:-}" = "--write-env" ] && WRITE=1
missing=0

req() { # req <label> <command>
	if have "$2"; then printf '  ok       %-22s %s\n' "$1" "$(command -v "$2")"
	else printf '  MISSING  %-22s (required)\n' "$1"; missing=1; fi
}
opt() { # opt <label> <command> <what needs it>
	if have "$2"; then printf '  ok       %-22s %s\n' "$1" "$(command -v "$2")"
	else printf '  missing  %-22s (optional: %s)\n' "$1" "$3"; fi
}
first_file() { for f in "$@"; do [ -f "$f" ] && { echo "$f"; return 0; }; done; return 1; }

log "host tools"
req git git; req make make; req curl curl
req "C compiler" cc
req "clang" clang
req "cmake" cmake
req "python3" python3
req rustup rustup; req cargo cargo; req rustc rustc
req "qemu x86_64" qemu-system-x86_64
opt "qemu aarch64" qemu-system-aarch64 "aarch64 images, ticket S12 and later"
opt sgdisk sgdisk "verify disk images"
opt mkfs.vfat mkfs.vfat "verify disk images"
opt mtools mdir "inspect FAT images"
opt strace strace "Linux syscall corpus (B05)"

log "firmware"
OVMF_CODE=$(first_file /usr/share/OVMF/OVMF_CODE_4M.fd /usr/share/OVMF/OVMF_CODE.fd /usr/share/edk2/ovmf/OVMF_CODE.fd /usr/share/edk2/x64/OVMF_CODE.4m.fd /usr/share/qemu/OVMF_CODE.fd || true)
OVMF_VARS=$(first_file /usr/share/OVMF/OVMF_VARS_4M.fd /usr/share/OVMF/OVMF_VARS.fd /usr/share/edk2/ovmf/OVMF_VARS.fd /usr/share/edk2/x64/OVMF_VARS.4m.fd /usr/share/qemu/OVMF_VARS.fd || true)
AAVMF_CODE=$(first_file /usr/share/AAVMF/AAVMF_CODE.fd /usr/share/edk2/aarch64/QEMU_EFI-pflash.raw /usr/share/qemu-efi-aarch64/QEMU_EFI.fd || true)
AAVMF_VARS=$(first_file /usr/share/AAVMF/AAVMF_VARS.fd /usr/share/edk2/aarch64/vars-template-pflash.raw || true)
if [ -n "$OVMF_CODE" ] && [ -n "$OVMF_VARS" ]; then printf '  ok       %-22s %s\n' "OVMF (x86_64 UEFI)" "$OVMF_CODE"
else printf '  MISSING  %-22s (required to run x86_64 images)\n' "OVMF (x86_64 UEFI)"; missing=1; fi
if [ -n "$AAVMF_CODE" ]; then printf '  ok       %-22s %s\n' "AAVMF (aarch64 UEFI)" "$AAVMF_CODE"
else printf '  missing  %-22s (optional: aarch64 images)\n' "AAVMF (aarch64 UEFI)"; fi

log "Rust toolchain (rust-toolchain.toml)"
if have rustup; then
	channel=$(sed -n 's/^channel *= *"\(.*\)"/\1/p' "$ROOT/rust-toolchain.toml" | head -n 1)
	if rustup toolchain list 2>/dev/null | grep -q "^$channel"; then printf '  ok       %-22s %s\n' "toolchain $channel" installed
	else printf '  MISSING  %-22s (run: make setup)\n' "toolchain $channel"; missing=1; fi
	installed=$(cd "$ROOT" && rustup target list --installed 2>/dev/null || true)
	for t in $(awk '/^targets *= *\[/{f=1;next} f&&/\]/{f=0} f{print}' "$ROOT/rust-toolchain.toml" | tr -d ' ",'); do
		if printf '%s\n' "$installed" | grep -qx "$t"; then printf '  ok       %-22s\n' "target $t"
		else printf '  MISSING  %-22s (run: make setup)\n' "target $t"; missing=1; fi
	done
	# cargo must also work OUTSIDE the repo (scratch dirs): a corrupt default toolchain breaks it there.
	# Read-only probe — project scripts never modify the host/default toolchain; the fix is manual.
	tmpd=$(mktemp -d)
	if (cd "$tmpd" && cargo --version >/dev/null 2>&1 && rustc --version >/dev/null 2>&1); then
		printf '  ok       %-22s %s\n' "cargo outside repo" "$(cd "$tmpd" && cargo --version)"
	else
		printf '  MISSING  %-22s (host issue; fix rustup manually, scripts never touch the host toolchain)\n' "cargo outside repo"
		missing=1
	fi
	rm -rf "$tmpd"
fi

if [ "$WRITE" -eq 1 ]; then
	{
		echo "# generated by scripts/doctor.sh: firmware paths found on this machine (ignored by git)"
		[ -n "$OVMF_CODE" ] && echo "export RAVEN_OVMF_CODE := $OVMF_CODE"
		[ -n "$OVMF_VARS" ] && echo "export RAVEN_OVMF_VARS := $OVMF_VARS"
		[ -n "$AAVMF_CODE" ] && echo "export RAVEN_AAVMF_CODE := $AAVMF_CODE"
		[ -n "$AAVMF_VARS" ] && echo "export RAVEN_AAVMF_VARS := $AAVMF_VARS"
	} > "$ROOT/.raven-env.mk"
	log "wrote .raven-env.mk"
fi

if [ "$missing" -eq 0 ]; then log "doctor: all required items present"; else warn "doctor: required items are missing (run: make setup)"; fi
exit "$missing"
