//! Generate the CJK table sources from the musl headers.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

const MUSL_REV: &str = "7813e9119eb5fe681b6750b8a033a0490bca0941";

fn read(path: &Path) -> String {
    fs::read_to_string(path).unwrap_or_else(|error| panic!("{}: {error}", path.display()))
}

fn numbers(text: &str) -> Vec<u16> {
    let mut out = Vec::new();
    let mut value: Option<u64> = None;
    for byte in text.bytes() {
        if byte.is_ascii_digit() {
            value = Some(value.unwrap_or(0) * 10 + u64::from(byte - b'0'));
        } else if let Some(number) = value.take() {
            out.push(u16::try_from(number).expect("table value fits u16"));
        }
    }
    if let Some(number) = value {
        out.push(u16::try_from(number).expect("table value fits u16"));
    }
    out
}

fn writeln_array(out: &mut String, name: &str, rows: usize, cols: usize, data: &[u16]) {
    assert_eq!(data.len(), rows * cols, "{name} dimensions");
    let _ = writeln!(out, "/// {name}.");
    let _ = writeln!(out, "#[rustfmt::skip]");
    let _ = writeln!(out, "pub static {name}: [[u16; {cols}]; {rows}] = [");
    for row in 0..rows {
        out.push_str("    [");
        for col in 0..cols {
            let index = row * cols + col;
            if col != 0 {
                out.push_str(", ");
            }
            let _ = write!(out, "{}", data.get(index).copied().unwrap_or(0));
        }
        out.push_str("],\n");
    }
    out.push_str("];\n");
}

fn writeln_flat(out: &mut String, name: &str, data: &[u16]) {
    let _ = writeln!(out, "/// {name}.");
    let _ = writeln!(out, "#[rustfmt::skip]");
    let _ = writeln!(out, "pub static {name}: [u16; {}] = [", data.len());
    for (index, value) in data.iter().enumerate() {
        if index % 12 == 0 {
            out.push_str("    ");
        }
        let _ = write!(out, "{value}, ");
        if index % 12 == 11 {
            out.push('\n');
        }
    }
    out.push_str("\n];\n");
}

fn main() {
    let dir = PathBuf::from(
        std::env::args()
            .nth(1)
            .expect("usage: gen_tables <musl/src/locale>"),
    );
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("cargo manifest dir"));
    let out_dir = manifest.join("src");

    let jis = numbers(&read(&dir.join("jis0208.h")));
    let rev = numbers(&read(&dir.join("revjis.h")));
    let gb = numbers(&read(&dir.join("gb18030.h")));
    let big5 = numbers(&read(&dir.join("big5.h")));
    let hkscs = numbers(&read(&dir.join("hkscs.h")));
    let ksc = numbers(&read(&dir.join("ksc.h")));
    let pairs_text = read(&dir.join("gb18030utf.h"));
    let pairs = pairs_text
        .split('{')
        .skip(1)
        .filter_map(|part| {
            let body = part.split('}').next()?;
            let mut values = body.split(',').filter_map(|value| {
                let value = value.trim();
                if let Some(hex) = value.strip_prefix("0x") {
                    u16::from_str_radix(hex, 16).ok()
                } else {
                    value.parse::<u16>().ok()
                }
            });
            Some((values.next()?, values.next()?))
        })
        .collect::<Vec<_>>();

    let mut jis_out = format!(
        "// SPDX-License-Identifier: MIT\n// Copyright (c) 2005-2020 Rich Felker, et al.\n// Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors\n// Generated by examples/gen_tables.rs from musl {MUSL_REV}; do not edit.\n// RavenBSD: transpiled from the pinned donor; see PROVENANCE.toml.\n"
    );
    writeln_array(&mut jis_out, "JIS0208", 84, 94, &jis);
    fs::write(out_dir.join("jis0208.rs"), jis_out).expect("write jis");

    let mut rev_out = format!(
        "// SPDX-License-Identifier: MIT\n// Copyright (c) 2005-2020 Rich Felker, et al.\n// Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors\n// Generated by examples/gen_tables.rs from musl {MUSL_REV}; do not edit.\n// RavenBSD: transpiled from the pinned donor; see PROVENANCE.toml.\n"
    );
    writeln_flat(&mut rev_out, "REVJIS", &rev);
    fs::write(out_dir.join("revjis.rs"), rev_out).expect("write revjis");

    let mut gb_out = format!(
        "// SPDX-License-Identifier: MIT\n// Copyright (c) 2005-2020 Rich Felker, et al.\n// Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors\n// Generated by examples/gen_tables.rs from musl {MUSL_REV}; do not edit.\n// RavenBSD: transpiled from the pinned donor; see PROVENANCE.toml.\n"
    );
    writeln_array(&mut gb_out, "GB18030", 126, 190, &gb);
    fs::write(out_dir.join("gb18030.rs"), gb_out).expect("write gb");

    let mut big5_out = format!(
        "// SPDX-License-Identifier: MIT\n// Copyright (c) 2005-2020 Rich Felker, et al.\n// Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors\n// Generated by examples/gen_tables.rs from musl {MUSL_REV}; do not edit.\n// RavenBSD: transpiled from the pinned donor; see PROVENANCE.toml.\n"
    );
    writeln_array(&mut big5_out, "BIG5", 89, 157, &big5);
    fs::write(out_dir.join("big5.rs"), big5_out).expect("write big5");

    let mut hkscs_out = format!(
        "// SPDX-License-Identifier: MIT\n// Copyright (c) 2005-2020 Rich Felker, et al.\n// Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors\n// Generated by examples/gen_tables.rs from musl {MUSL_REV}; do not edit.\n// RavenBSD: transpiled from the pinned donor; see PROVENANCE.toml.\n"
    );
    writeln_flat(&mut hkscs_out, "HKSCS", &hkscs);
    fs::write(out_dir.join("hkscs.rs"), hkscs_out).expect("write hkscs");

    let mut ksc_out = format!(
        "// SPDX-License-Identifier: MIT\n// Copyright (c) 2005-2020 Rich Felker, et al.\n// Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors\n// Generated by examples/gen_tables.rs from musl {MUSL_REV}; do not edit.\n// RavenBSD: transpiled from the pinned donor; see PROVENANCE.toml.\n"
    );
    writeln_array(&mut ksc_out, "KSC", 93, 94, &ksc);
    fs::write(out_dir.join("ksc.rs"), ksc_out).expect("write ksc");

    let mut pairs_out = format!(
        "// SPDX-License-Identifier: MIT\n// Copyright (c) 2005-2020 Rich Felker, et al.\n// Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors\n// Generated by examples/gen_tables.rs from musl {MUSL_REV}; do not edit.\n// RavenBSD: transpiled from the pinned donor; see PROVENANCE.toml.\n"
    );
    let _ = writeln!(pairs_out, "/// GB18030 four-byte supplement.");
    let _ = writeln!(pairs_out, "#[rustfmt::skip]");
    let _ = writeln!(
        pairs_out,
        "pub static GB18030UTF: [[u16; 2]; {}] = [",
        pairs.len()
    );
    for (left, right) in &pairs {
        let _ = writeln!(pairs_out, "    [{left}, {right}],");
    }
    pairs_out.push_str("];\n");
    fs::write(out_dir.join("gb18030utf.rs"), pairs_out).expect("write gb18030utf");
}
