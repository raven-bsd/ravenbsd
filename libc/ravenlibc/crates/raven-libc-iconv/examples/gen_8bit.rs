//! Generate `tables_8bit.rs` from the musl codepage blobs.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

const MUSL_REV: &str = "7813e9119eb5fe681b6750b8a033a0490bca0941";

fn read(path: &Path) -> String {
    fs::read_to_string(path).unwrap_or_else(|error| panic!("{}: {error}", path.display()))
}

fn decode_strings(text: &str) -> Vec<u8> {
    let mut out = Vec::new();
    let mut chars = text.chars().peekable();
    while let Some(ch) = chars.next() {
        if ch != '"' {
            continue;
        }
        while let Some(ch) = chars.next() {
            match ch {
                '"' => break,
                '\\' => {
                    let Some(next) = chars.next() else { break };
                    if next.is_ascii_digit() {
                        let mut value = next.to_digit(8).unwrap_or(0);
                        for _ in 0..2 {
                            let Some(digit) = chars.peek().and_then(|value| value.to_digit(8))
                            else {
                                break;
                            };
                            chars.next();
                            value = value * 8 + digit;
                        }
                        out.push((value & 0xff) as u8);
                    } else {
                        out.push(next as u8);
                    }
                }
                other => out.push(other as u8),
            }
        }
    }
    out
}

fn numbers(text: &str) -> Vec<u16> {
    let mut out = Vec::new();
    let mut value: Option<u64> = None;
    for byte in text.bytes() {
        if byte.is_ascii_digit() {
            value = Some(value.unwrap_or(0) * 10 + u64::from(byte - b'0'));
        } else if let Some(number) = value.take() {
            out.push(u16::try_from(number).expect("legacy char fits u16"));
        }
    }
    if let Some(number) = value {
        out.push(u16::try_from(number).expect("legacy char fits u16"));
    }
    out
}

fn main() {
    let dir = PathBuf::from(
        std::env::args()
            .nth(1)
            .expect("usage: gen_8bit <musl/src/locale>"),
    );
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("cargo manifest dir"));
    let charmap = decode_strings(&read(&dir.join("codepages.h")));
    let legacy = numbers(&read(&dir.join("legacychars.h")));

    let mut out = format!(
        "// SPDX-License-Identifier: MIT\n// Copyright (c) 2005-2020 Rich Felker, et al.\n// Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors\n// Generated by examples/gen_8bit.rs from musl {MUSL_REV}; do not edit.\n// RavenBSD: transpiled from the pinned donor; see PROVENANCE.toml.\n"
    );
    let _ = writeln!(out, "/// The musl `charmaps` alias/table blob.");
    let _ = writeln!(out, "#[rustfmt::skip]");
    let _ = writeln!(out, "pub static CHARMAPS: &[u8] = &[");
    for (index, byte) in charmap.iter().enumerate() {
        if index % 16 == 0 {
            out.push_str("    ");
        }
        let _ = write!(out, "{byte}, ");
        if index % 16 == 15 {
            out.push('\n');
        }
    }
    out.push_str("\n];\n");
    let _ = writeln!(out, "/// The shared legacy-character table.");
    let _ = writeln!(out, "#[rustfmt::skip]");
    let _ = writeln!(out, "pub static LEGACY_CHARS: &[u16] = &[");
    for (index, value) in legacy.iter().enumerate() {
        if index % 12 == 0 {
            out.push_str("    ");
        }
        let _ = write!(out, "{value}, ");
        if index % 12 == 11 {
            out.push('\n');
        }
    }
    out.push_str("\n];\n");
    fs::write(manifest.join("src/tables_8bit.rs"), out).expect("write tables_8bit.rs");
}
