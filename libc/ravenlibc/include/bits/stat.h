/* RavenBSD: cdefs.h defines __unused as an attribute macro; the donor field
 * name must survive in the frozen struct stat layout. */
#pragma push_macro("__unused")
#undef __unused

struct stat {
	dev_t st_dev;
	ino_t st_ino;
	mode_t st_mode;
	nlink_t st_nlink;
	uid_t st_uid;
	gid_t st_gid;
	dev_t st_rdev;
	unsigned long long __pad;
	off_t st_size;
	blksize_t st_blksize;
	int __pad2;
	blkcnt_t st_blocks;
	struct timespec st_atim;
	struct timespec st_mtim;
	struct timespec st_ctim;
	unsigned __unused[2];
};
#pragma pop_macro("__unused")
