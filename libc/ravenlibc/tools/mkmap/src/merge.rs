//!
//! `Symbol.map` merge: the version-script body and the flat `Symbols.list`.

use anyhow::{Result, bail};

use crate::versions::{Node, NodeBody, Symbol};

/// The result of one merge.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Merged {
    /// The complete `libc.map` linker version script.
    pub map: String,
    /// The flat `Symbols.list` file.
    pub list: String,
    /// Public names, sorted.
    pub public: Vec<String>,
    /// Private (`RAVENprivate_*`) names, sorted.
    pub private: Vec<String>,
}

/// Merge a parsed `Versions.def` and every `Symbol.map`.
///
/// # Errors
/// A body for a node that `Versions.def` does not define, the same name in two nodes, a
/// private node that is not last, or a missing `RAVENprivate_*` node.
pub fn merge(versions: &[Node], bodies: &[NodeBody], arch: &str) -> Result<Merged> {
    if versions.is_empty() {
        bail!("Versions.def has no node");
    }
    for body in bodies {
        if !versions.iter().any(|node| node.name == body.node) {
            bail!(
                "Symbol.map names node `{}`, absent from Versions.def",
                body.node
            );
        }
    }
    let last = versions.iter().next_back().map(|node| node.name.as_str());
    let private_node = versions
        .iter()
        .find(|node| node.name.starts_with("RAVENprivate"));
    let Some(private_node) = private_node else {
        bail!("Versions.def has no RAVENprivate_* node");
    };
    if last != Some(private_node.name.as_str()) {
        bail!("the RAVENprivate_* node must be the last node of the chain");
    }

    let mut public: Vec<String> = Vec::new();
    let mut private: Vec<String> = Vec::new();
    let mut seen: Vec<(String, String)> = Vec::new();
    let mut per_node: Vec<Vec<String>> = vec![Vec::new(); versions.len()];

    for body in bodies {
        let Some(slot) = versions.iter().position(|node| node.name == body.node) else {
            continue;
        };
        for symbol in &body.symbols {
            if let Some((existing, node)) =
                seen.iter().find(|(name, _)| name == &symbol.name).cloned()
            {
                bail!(
                    "symbol `{existing}` appears in both `{node}` and `{}`",
                    body.node
                );
            }
            seen.push((symbol.name.clone(), body.node.clone()));
            if !symbol.on_arch(arch) {
                continue;
            }
            if body.node == private_node.name {
                private.push(symbol.name.clone());
            } else {
                public.push(symbol.name.clone());
            }
            if let Some(list) = per_node.get_mut(slot) {
                list.push(symbol.name.clone());
            }
        }
    }
    public.sort();
    public.dedup();
    private.sort();
    private.dedup();

    let map = render_map(versions, &per_node, private_node.name.as_str());
    let list = render_list(&public, &private);
    Ok(Merged {
        map,
        list,
        public,
        private,
    })
}

/// Render the linker version script.
fn render_map(versions: &[Node], per_node: &[Vec<String>], private_node: &str) -> String {
    let mut out = String::new();
    out.push_str("# SPDX-License-Identifier: BSD-3-Clause\n");
    out.push_str("# Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors\n");
    out.push_str(
        "#\n# Generated by raven-libc-mkmap from abi/Versions.def and Symbol.map bodies.\n",
    );
    for (index, node) in versions.iter().enumerate() {
        out.push_str(&node.name);
        out.push_str(" {\n");
        out.push_str("\tglobal:\n");
        if let Some(symbols) = per_node.get(index) {
            for symbol in symbols {
                out.push('\t');
                out.push('\t');
                out.push_str(symbol);
                out.push_str(";\n");
            }
        }
        if node.name == private_node {
            out.push_str("\tlocal:\n\t\t*;\n");
        }
        match &node.parent {
            Some(parent) => {
                out.push_str("} ");
                out.push_str(parent);
                out.push_str(";\n");
            }
            None => out.push_str("};\n"),
        }
    }
    out
}

/// Render `abi/Symbols.list`.
fn render_list(public: &[String], private: &[String]) -> String {
    let mut out = String::new();
    out.push_str("# SPDX-License-Identifier: BSD-3-Clause\n");
    out.push_str("# Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors\n");
    out.push_str("#\n");
    out.push_str("# Generated by raven-libc-mkmap; do not edit. Static libc.a and shared\n");
    out.push_str("# libc.so.1 export the same public names (A-abi-7); the private node\n");
    out.push_str("# follows the private marker below.\n");
    for name in public {
        out.push_str(name);
        out.push('\n');
    }
    out.push_str("# private\n");
    for name in private {
        out.push_str(name);
        out.push('\n');
    }
    out
}

/// Split a `Symbols.list` back into its public and private sections.
#[must_use]
pub fn parse_list(text: &str) -> (Vec<String>, Vec<String>) {
    let mut public = Vec::new();
    let mut private = Vec::new();
    let mut in_private = false;
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            if line == "# private" {
                in_private = true;
            }
            continue;
        }
        if in_private {
            private.push(line.to_string());
        } else {
            public.push(line.to_string());
        }
    }
    (public, private)
}

/// The names of one node body, in file order.
#[must_use]
pub fn body_symbols(body: &NodeBody) -> Vec<&Symbol> {
    body.symbols.iter().collect()
}

