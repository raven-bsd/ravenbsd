//!
//! `freeze`: record one released DSO node as `frozen/<node>.txt`.
//!
//! The file is the release contract: one sorted line `name kind size arches` per symbol, with
//! `F` for a function and `D` for data. It is never edited by hand, and a differing existing
//! file is refused instead of overwritten.

use std::path::Path;

use anyhow::{Context, Result, bail};

use crate::tools::{DynSymbol, parse_dyn_syms};

/// Render the frozen file for one node.
#[must_use]
pub fn render(symbols: &[DynSymbol], node: &str, arch: &str) -> String {
    let mut lines = symbols
        .iter()
        .filter(|symbol| symbol.version == node)
        .map(|symbol| {
            let kind = if symbol.kind == "FUNC" { 'F' } else { 'D' };
            format!("{} {} {} {arch}", symbol.name, kind, symbol.size)
        })
        .collect::<Vec<_>>();
    lines.sort();
    let mut out = String::from("# SPDX-License-Identifier: BSD-3-Clause\n");
    out.push_str("# Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors\n");
    out.push_str("# Generated by raven-libc-mkmap freeze; do not edit.\n");
    for line in lines {
        out.push_str(&line);
        out.push('\n');
    }
    out
}

/// Write the frozen file, refusing to replace a different one.
///
/// # Errors
/// An existing file with other content, or an I/O error.
pub fn write(out_dir: &Path, node: &str, rendered: &str) -> Result<()> {
    if node.is_empty() || node.contains('/') {
        bail!("invalid node name `{node}`");
    }
    std::fs::create_dir_all(out_dir)
        .with_context(|| format!("cannot create {}", out_dir.display()))?;
    let path = out_dir.join(format!("{node}.txt"));
    if path.is_file() {
        let existing = std::fs::read_to_string(&path)
            .with_context(|| format!("cannot read {}", path.display()))?;
        if existing != rendered {
            bail!(
                "{} already exists with different content; a frozen node is never rewritten",
                path.display()
            );
        }
        return Ok(());
    }
    std::fs::write(&path, rendered).with_context(|| format!("cannot write {}", path.display()))
}

/// Run `freeze` over a DSO.
///
/// # Errors
/// A missing tool or a read/parse failure.
pub fn run(so: &Path, node: &str, out_dir: &Path, arch: &str, root: &Path) -> Result<String> {
    let program = crate::tools::readelf_program();
    let path = so.display().to_string();
    let output = crate::tools::run(&program, &["--dyn-syms", "-W", &path], root)?;
    let symbols = parse_dyn_syms(&output);
    if symbols.is_empty() {
        bail!("no defined dynamic symbol in {path}");
    }
    let rendered = render(&symbols, node, arch);
    write(out_dir, node, &rendered)?;
    Ok(rendered)
}

