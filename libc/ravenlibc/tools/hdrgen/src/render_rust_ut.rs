fn renders_eighteen_files() {
    let Some(files) = files() else {
        return;
    };
    assert_eq!(files.len(), 18);
    for name in [
        "mod.rs",
        "types.rs",
        "structs.rs",
        "layout_table.rs",
        "errno.rs",
        "signal.rs",
        "fcntl.rs",
        "mman.rs",
        "stat.rs",
        "socket.rs",
        "netinet.rs",
        "poll.rs",
        "time.rs",
        "resource.rs",
        "limits.rs",
        "sysconf.rs",
        "pthread.rs",
        "misc.rs",
    ] {
        assert!(files.contains_key(name), "{name}");
    }
}

#[test]
fn every_file_starts_with_an_spdx_line() {
    let Some(files) = files() else {
        return;
    };
    for (name, text) in files {
        let first = text.lines().next().unwrap_or("");
        assert!(
            first.contains("SPDX-License-Identifier:"),
            "{name}: {first}"
        );
    }
}

#[test]
fn musl_group_files_carry_the_notice_and_revision() {
    let Some(files) = files() else {
        return;
    };
    for name in ["limits.rs", "socket.rs", "misc.rs"] {
        let text = &files[name];
        assert!(
            text.contains("Copyright © 2005-2020 Rich Felker, et al."),
            "{name}"
        );
        assert!(text.contains("RavenBSD: transpiled from musl:"), "{name}");
        assert!(
            text.contains("@ 7813e9119eb5fe681b6750b8a033a0490bca0941"),
            "{name}"
        );
        assert!(text.contains("Permission is hereby granted"), "{name}");
    }
}

#[test]
fn freebsd_group_files_carry_the_reviewed_notice_and_revision() {
    let Some(files) = files() else {
        return;
    };
    for (name, donor) in [
        ("errno.rs", "freebsd:sys/sys/errno.h"),
        ("signal.rs", "freebsd:sys/sys/signal.h"),
    ] {
        let text = &files[name];
        assert!(
            text.contains("SPDX-License-Identifier: BSD-3-Clause"),
            "{text}"
        );
        assert!(
            text.contains(&format!("RavenBSD: derived from {donor}")),
            "{text}"
        );
        assert!(
            text.contains("@ 133344405f532bd54ff3629a77d4c4e062f01fdb"),
            "{text}"
        );
        assert!(!text.contains("Permission is hereby granted"), "{text}");
    }
}

