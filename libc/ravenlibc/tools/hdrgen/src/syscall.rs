//! `arch/<a>/bits/syscall.h` from the `raven-linux-abi` syscall tables.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use anyhow::{Context, Result};

use crate::model::ARCHES;

/// The syscall table of one architecture.
#[must_use]
pub fn table(arch: &str) -> Option<&'static [(&'static str, u32)]> {
    match arch {
        "x86_64" => Some(raven_linux_abi::sysnums::X86_64),
        "aarch64" => Some(raven_linux_abi::sysnums::AARCH64),
        "riscv64" => Some(raven_linux_abi::sysnums::RISCV64),
        _ => None,
    }
}

/// Render the syscall header for `arch`.
pub fn render(arch: &str, linux_raw_sys_rev: &str) -> Result<String> {
    let table = table(arch).with_context(|| format!("no syscall table for {arch}"))?;
    let mut out = String::new();
    out.push_str("/*\n");
    out.push_str(" * SPDX-License-Identifier: MIT\n");
    out.push_str(" * Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors\n");
    out.push_str(" *\n");
    let _ = writeln!(
        out,
        " * Generated by raven-libc-hdrgen from raven-linux-abi::sysnums ({arch}). Do not edit."
    );
    let _ = writeln!(
        out,
        " * Source: linux-raw-sys {linux_raw_sys_rev} src/{arch}/general.rs (MIT)"
    );
    out.push_str(" */\n\n");
    let mut entries: Vec<&(&str, u32)> = table.iter().collect();
    entries.sort_by(|left, right| left.0.cmp(right.0));
    for (name, number) in entries {
        let _ = writeln!(out, "#define __NR_{name} {number}");
        let _ = writeln!(out, "#define SYS_{name} __NR_{name}");
    }
    Ok(out)
}

/// Render all three syscall headers, keyed by `arch/<a>/bits/syscall.h`.
pub fn render_all(linux_raw_sys_rev: &str) -> Result<BTreeMap<String, String>> {
    let mut files = BTreeMap::new();
    for arch in ARCHES {
        files.insert(
            format!("arch/{arch}/bits/syscall.h"),
            render(arch, linux_raw_sys_rev)?,
        );
    }
    Ok(files)
}

/// Number of syscall names in a table (each yields two `#define` lines).
#[cfg(test)]
#[must_use]
pub fn table_len(arch: &str) -> Option<usize> {
    table(arch).map(<[_]>::len)
}

/// Look up one syscall number, for tests and documentation.
#[cfg(test)]
#[must_use]
pub fn number(arch: &str, name: &str) -> Option<u32> {
    table(arch)?
        .iter()
        .find(|(candidate, _)| *candidate == name)
        .map(|(_, number)| *number)
}

