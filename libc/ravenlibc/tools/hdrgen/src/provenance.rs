/// Comment syntax of a generated file.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CommentStyle {
    /// `// ...` (Rust).
    LineSlash,
    /// `# ...` (TOML). Kept so the notice renderer covers every syntax a derived file can
    /// use; the committed TOMLs carry hand-written notices today.
    #[allow(dead_code)]
    LineHash,
    /// `/* ... */` (C).
    BlockC,
}

impl CommentStyle {
    fn wrap(self, lines: &[&str]) -> String {
        match self {
            Self::LineSlash => lines
                .iter()
                .map(|line| {
                    if line.is_empty() {
                        "//".to_string()
                    } else {
                        format!("// {line}")
                    }
                })
                .collect::<Vec<_>>()
                .join("\n"),
            Self::LineHash => lines
                .iter()
                .map(|line| {
                    if line.is_empty() {
                        "#".to_string()
                    } else {
                        format!("# {line}")
                    }
                })
                .collect::<Vec<_>>()
                .join("\n"),
            Self::BlockC => {
                let mut out = String::from("/*\n");
                for line in lines {
                    if line.is_empty() {
                        out.push_str(" *\n");
                    } else {
                        let _ = writeln!(out, " * {line}");
                    }
                }
                out.push_str(" */");
                out
            }
        }
    }
}

/// The exact musl-derived notice block of doc 14 section 9.
#[must_use]
pub fn musl_notice(style: CommentStyle, upstream_path: &str, revision: &str) -> String {
    let mut lines: Vec<String> = vec![
        "SPDX-License-Identifier: MIT".to_string(),
        "Copyright © 2005-2020 Rich Felker, et al.".to_string(),
        "Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors".to_string(),
        String::new(),
        format!("RavenBSD: transpiled from musl:{upstream_path} @ {revision}"),
        "(no per-file header; covered by musl/COPYRIGHT, H-1; constants transcribed to TOML and \
         generated)"
            .to_string(),
        String::new(),
    ];
    lines.extend(MUSL_MIT_TEXT.iter().map(|line| (*line).to_string()));
    let borrowed: Vec<&str> = lines.iter().map(String::as_str).collect();
    style.wrap(&borrowed)
}

/// The first-party header for a generated file.
#[must_use]
pub fn first_party_generated(source: &str) -> String {
    format!(
        "// SPDX-License-Identifier: BSD-3-Clause\n\
         // Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors\n\
         //\n\
         // Generated by raven-libc-hdrgen from abi/{source}. Do not edit.\n"
    )
}

/// Revisions read from `donors.lock`.
#[derive(Debug, Clone)]
pub struct Lock {
    /// The pinned musl commit.
    pub musl: String,
    /// The pinned `linux-raw-sys` commit.
    pub linux_raw_sys: String,
}

/// Find `ravenbsd-resources/donors.lock` at or above `start`.
#[must_use]
pub fn discover_resources(start: &Path) -> Option<PathBuf> {
    let mut directory = Some(start);
    while let Some(current) = directory {
        let candidate = current.join("ravenbsd-resources");
        if candidate.join("donors.lock").is_file() {
            return Some(candidate);
        }
        directory = current.parent();
    }
    None
}

/// Read the two revisions hdrgen pins its outputs to.
pub fn read_lock(resources: &Path) -> Result<Lock> {
    let path = resources.join("donors.lock");
    let text = std::fs::read_to_string(&path)
        .with_context(|| format!("cannot read {}", path.display()))?;
    let mut musl = None;
    let mut linux_raw_sys = None;
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let mut fields = line.split_whitespace();
        let (Some(name), Some(sha)) = (fields.next(), fields.next()) else {
            continue;
        };
        match name {
            "musl" => musl = Some(sha.to_string()),
            "linux-raw-sys" => linux_raw_sys = Some(sha.to_string()),
            _ => {}
        }
    }
    Ok(Lock {
        musl: musl.context("donors.lock has no musl entry")?,
        linux_raw_sys: linux_raw_sys.context("donors.lock has no linux-raw-sys entry")?,
    })
}

/// One `[[import]]` entry.
#[derive(Debug, Clone)]
pub struct ImportEntry {
    /// Repository-relative path.
    pub path: String,
    /// Donor name.
    pub upstream: String,
    /// Donor source path(s).
    pub upstream_path: String,
    /// Donor revision.
    pub upstream_rev: String,
    /// Licence.
    pub license: String,
    /// Tier.
    pub tier: String,
    /// Copy date.
    pub copied: String,
    /// Always true for transcribed files.
    pub modified: bool,
    /// Free-form note.
    pub notes: String,
}

impl ImportEntry {
    /// Render the entry in the root `PROVENANCE.toml` format.
    #[must_use]
    pub fn render(&self) -> String {
        format!(
            "[[import]]\npath = \"{}\"\nupstream = \"{}\"\nupstream_path = \"{}\"\n\
             upstream_rev = \"{}\"\nlicense = \"{}\"\ntier = \"{}\"\ncopied = \"{}\"\n\
             modified = {}\nnotes = \"{}\"\n",
            self.path,
            self.upstream,
            self.upstream_path,
            self.upstream_rev,
            self.license,
            self.tier,
            self.copied,
            self.modified,
            self.notes
        )
    }
}

/// Build every `[[import]]` entry from the loaded tables.
#[must_use]
pub fn import_entries(tables: &Tables, date: &str, lock: &Lock) -> Vec<ImportEntry> {
    let mut entries = Vec::new();
    for group in &tables.groups {
        let stem = &group.stem;
        let upstream = group.def.source.join(", ");
        let notes = format!(
            "no per-file header; covered by musl/COPYRIGHT; checkout {}; constants transcribed \
             into abi/{stem}.toml; deviations in abi/deviations.toml",
            lock.musl
        );
        let header = expected_header(stem);
        let paths = [
            format!("libc/ravenlibc/abi/{stem}.toml"),
            format!("libc/ravenlibc/crates/raven-libc-abi/src/generated/{stem}.rs"),
            format!("libc/ravenlibc/abi/generated/include/{header}"),
        ];
        for path in paths {
            entries.push(ImportEntry {
                path,
                upstream: "musl".to_string(),
                upstream_path: upstream.clone(),
                upstream_rev: lock.musl.clone(),
                license: "MIT".to_string(),
                tier: "A".to_string(),
                copied: date.to_string(),
                modified: true,
                notes: notes.clone(),
            });
        }
    }
    for arch in crate::model::ARCHES {
        entries.push(ImportEntry {
            path: format!("libc/ravenlibc/abi/generated/include/arch/{arch}/bits/syscall.h"),
            upstream: "linux-raw-sys".to_string(),
            upstream_path: format!("src/{arch}/general.rs"),
            upstream_rev: lock.linux_raw_sys.clone(),
            license: "MIT".to_string(),
            tier: "A".to_string(),
            copied: date.to_string(),
            modified: true,
            notes: "via crates/raven-linux-abi sysnums".to_string(),
        });
    }
    entries.sort_by(|left, right| left.path.cmp(&right.path));
    entries
}

/// Validate a `--date` argument.
pub fn validate_date(date: &str) -> Result<()> {
    let bytes = date.as_bytes();
    if bytes.len() != 10 || bytes[4] != b'-' || bytes[7] != b'-' {
        bail!("--date must be YYYY-MM-DD, found {date:?}");
    }
    if !bytes
        .iter()
        .enumerate()
        .all(|(index, byte)| index == 4 || index == 7 || byte.is_ascii_digit())
    {
        bail!("--date must be YYYY-MM-DD, found {date:?}");
    }
    Ok(())
}

