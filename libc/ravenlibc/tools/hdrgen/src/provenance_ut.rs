//! Unit tests for the notice, lock and import machinery.

use super::*;
use crate::validate;

fn tables() -> Tables {
    let abi = std::path::PathBuf::from(concat!(env!("CARGO_MANIFEST_DIR"), "/../../../.."))
        .join("libc/ravenlibc/abi");
    validate::load(&abi).expect("tables")
}

fn resources() -> PathBuf {
    let here = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    discover_resources(&here).expect("ravenbsd-resources")
}

#[test]
fn musl_notice_line_comment() {
    let notice = musl_notice(CommentStyle::LineSlash, "include/errno.h", "abc");
    let lines: Vec<&str> = notice.lines().collect();
    assert_eq!(lines[0], "// SPDX-License-Identifier: MIT");
    assert_eq!(lines[1], "// Copyright © 2005-2020 Rich Felker, et al.");
    assert!(lines[4].contains("RavenBSD: transpiled from musl:include/errno.h @ abc"));
    assert!(notice.contains("// Permission is hereby granted"));
}

#[test]
fn musl_notice_hash_and_block_comments() {
    let hash = musl_notice(CommentStyle::LineHash, "x", "y");
    assert!(hash.starts_with("# SPDX-License-Identifier: MIT"));
    let block = musl_notice(CommentStyle::BlockC, "x", "y");
    assert!(block.starts_with("/*\n * SPDX-License-Identifier: MIT"));
    assert!(block.ends_with(" */"));
}

#[test]
fn first_party_header_names_the_source() {
    let text = first_party_generated("types.toml");
    assert!(text.contains("SPDX-License-Identifier: BSD-3-Clause"));
    assert!(text.contains("Generated by raven-libc-hdrgen from abi/types.toml. Do not edit."));
}

#[test]
fn discovers_the_resources_tree() {
    let found = resources();
    assert!(found.join("donors.lock").is_file());
    assert_eq!(
        found.file_name().and_then(|name| name.to_str()),
        Some("ravenbsd-resources")
    );
}

#[test]
fn reads_the_pinned_revisions() {
    let lock = read_lock(&resources()).expect("lock");
    assert_eq!(lock.musl, "7813e9119eb5fe681b6750b8a033a0490bca0941");
    assert_eq!(
        lock.linux_raw_sys,
        "3b15c17f2688445cd3e9ef2907113829837773dd"
    );
}

#[test]
fn import_entries_cover_every_derived_file() {
    let tables = tables();
    let lock = read_lock(&resources()).expect("lock");
    let entries = import_entries(&tables, "2026-11-13", &lock);
    assert_eq!(entries.len(), 45);
    let musl: Vec<&ImportEntry> = entries
        .iter()
        .filter(|entry| entry.upstream == "musl")
        .collect();
    let linux: Vec<&ImportEntry> = entries
        .iter()
        .filter(|entry| entry.upstream == "linux-raw-sys")
        .collect();
    assert_eq!(musl.len(), 42);
    assert_eq!(linux.len(), 3);
    assert!(entries.windows(2).all(|pair| pair[0].path < pair[1].path));
    for entry in &musl {
        assert_eq!(entry.license, "MIT");
        assert_eq!(entry.tier, "A");
        assert_eq!(entry.upstream_rev, lock.musl);
        assert!(entry.notes.contains("no per-file header"));
        assert!(
            entry
                .notes
                .contains("checkout 7813e9119eb5fe681b6750b8a033a0490bca0941")
        );
    }
    for entry in &linux {
        assert_eq!(entry.upstream_path.split('/').count(), 3);
        assert_eq!(entry.notes, "via crates/raven-linux-abi sysnums");
    }
}

#[test]
fn every_import_path_is_under_the_repository_roots() {
    let tables = tables();
    let lock = read_lock(&resources()).expect("lock");
    for entry in import_entries(&tables, "2026-11-13", &lock) {
        assert!(entry.path.starts_with("libc/ravenlibc/"), "{}", entry.path);
    }
}

#[test]
fn every_import_path_exists_in_the_repository() {
    let tables = tables();
    let lock = read_lock(&resources()).expect("lock");
    let root = std::path::PathBuf::from(concat!(env!("CARGO_MANIFEST_DIR"), "/../../../.."));
    for entry in import_entries(&tables, "2026-11-13", &lock) {
        assert!(
            root.join(&entry.path).is_file(),
            "import path does not exist: {}",
            entry.path
        );
    }
}

#[test]
fn rendered_entry_parses_as_toml() {
    let tables = tables();
    let lock = read_lock(&resources()).expect("lock");
    for entry in import_entries(&tables, "2026-11-13", &lock) {
        let text = entry.render();
        let parsed: toml::Value = toml::from_str(&text).expect("entry TOML");
        let table = parsed.as_table().expect("table");
        assert!(table.contains_key("import"));
    }
}

#[test]
fn date_validation() {
    assert!(validate_date("2026-11-13").is_ok());
    assert!(validate_date("2026-1-3").is_err());
    assert!(validate_date("not-a-date").is_err());
    assert!(validate_date("2026_11_13").is_err());
}
