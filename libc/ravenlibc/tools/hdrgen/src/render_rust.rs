//! Rendering of `crates/raven-libc-abi/src/generated/*.rs`.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use anyhow::{Context, Result, bail};

use crate::layout::{FieldType, opaque_layout};
use crate::model::{ARCHES, ConstDef, OpaqueDef, RecordDef, TypeDef};
use crate::provenance::{CommentStyle, first_party_generated, musl_notice};
use crate::validate::{Tables, layouts, rust_name};
use crate::values::{self, render_i128};

/// Render every generated Rust file, keyed by the bare file name under `src/generated`.
pub fn render_all(
    tables: &Tables,
    values: &crate::validate::Values,
    musl_rev: &str,
) -> Result<BTreeMap<String, String>> {
    let mut files = BTreeMap::new();
    files.insert("types.rs".to_string(), render_types(tables)?);
    files.insert("structs.rs".to_string(), render_structs(tables)?);
    files.insert("layout_table.rs".to_string(), render_layout_table(tables)?);
    for group in &tables.groups {
        let upstream = group.def.source.join(", ");
        let mut out = musl_notice(CommentStyle::LineSlash, &upstream, musl_rev);
        out.push('\n');
        let _ = writeln!(
            out,
            "// Generated by raven-libc-hdrgen from abi/{}.toml. Do not edit.",
            group.stem
        );
        out.push('\n');
        render_group(&mut out, &group.def, &group.stem, values)?;
        files.insert(format!("{}.rs", group.stem), out);
    }
    files.insert("mod.rs".to_string(), render_mod(tables));
    for text in files.values_mut() {
        while text.ends_with("\n\n") {
            text.pop();
        }
        if !text.ends_with('\n') {
            text.push('\n');
        }
    }
    Ok(files)
}

fn render_mod(tables: &Tables) -> String {
    let mut out = first_party_generated("mod.rs");
    out.push('\n');
    let mut modules: Vec<String> = tables
        .groups
        .iter()
        .map(|group| group.stem.clone())
        .collect();
    modules.push("layout_table".to_string());
    modules.push("structs".to_string());
    modules.push("types".to_string());
    modules.sort();
    for module in modules {
        let _ = writeln!(out, "pub mod {module};");
    }
    out
}

fn render_types(tables: &Tables) -> Result<String> {
    let mut out = first_party_generated("types.toml");
    out.push('\n');
    out.push_str("//! Scalar C types of the ravenlibc ABI, one alias per doc 14 3.A.2 row.\n\n");
    out.push_str("#![allow(non_camel_case_types)]\n\n");
    for ty in &tables.types.types {
        render_type(&mut out, ty)?;
    }
    let char = tables
        .types
        .types
        .iter()
        .find(|ty| ty.name == "char")
        .context("types.toml has no char row")?;
    out.push('\n');
    out.push_str("/// Whether plain `char` is signed on the target (doc 14 D2/H-14).\n");
    for arch in ARCHES {
        let signed = signedness(char, arch)?;
        let cfg = if arch == "x86_64" {
            "not(any(target_arch = \"aarch64\", target_arch = \"riscv64\"))".to_string()
        } else {
            format!("target_arch = \"{arch}\"")
        };
        let _ = writeln!(out, "#[cfg({cfg})]");
        let _ = writeln!(out, "pub const CHAR_IS_SIGNED: bool = {signed};");
    }
    out.push_str("\nconst _: () = assert!((core::ffi::c_char::MIN != 0) == CHAR_IS_SIGNED);\n");
    Ok(out)
}

fn render_type(out: &mut String, ty: &TypeDef) -> Result<()> {
    if ty.name == "char" {
        return Ok(());
    }
    if let Some(doc) = &ty.doc {
        let _ = writeln!(out, "/// {doc}");
    }
    if ty.per_arch.is_empty() {
        let _ = writeln!(out, "pub type {} = {};", ty.name, ty.rust);
        return Ok(());
    }
    let overridden: Vec<String> = ty
        .per_arch
        .keys()
        .map(|arch| format!("target_arch = \"{arch}\""))
        .collect();
    for arch in ARCHES {
        if let Some(override_) = ty.per_arch.get(arch) {
            let _ = writeln!(out, "#[cfg(target_arch = \"{arch}\")]");
            let _ = writeln!(out, "pub type {} = {};", ty.name, override_.rust);
        }
    }
    if ty.per_arch.len() < ARCHES.len() {
        let _ = writeln!(out, "#[cfg(not(any({})))]", overridden.join(", "));
        let _ = writeln!(out, "pub type {} = {};", ty.name, ty.rust);
    }
    Ok(())
}

fn signedness(ty: &TypeDef, arch: &str) -> Result<bool> {
    Ok(ty
        .per_arch
        .get(arch)
        .map_or(ty.signed, |override_| override_.signed))
}

fn render_structs(tables: &Tables) -> Result<String> {
    let mut out = first_party_generated("structs.toml");
    out.push('\n');
    out.push_str("//! `#[repr(C)]` records and sized opaque types of the ravenlibc ABI.\n\n");
    for record in &tables.structs.record {
        render_record(&mut out, tables, record)?;
    }
    for opaque in &tables.structs.opaque {
        render_opaque(&mut out, tables, opaque)?;
    }
    Ok(out)
}

fn rust_type(tables: &Tables, ty: &FieldType) -> String {
    match ty {
        FieldType::Int(name) => (*name).to_string(),
        FieldType::Ptr => "*mut core::ffi::c_void".to_string(),
        FieldType::CChar => "core::ffi::c_char".to_string(),
        FieldType::Array(element, length) => {
            format!("[{}; {length}]", rust_type(tables, element))
        }
        FieldType::Named(name) => rust_name(tables, name).unwrap_or(name).to_string(),
    }
}

fn zero_value(tables: &Tables, ty: &FieldType) -> String {
    match ty {
        FieldType::Int(_) | FieldType::CChar => "0".to_string(),
        FieldType::Ptr => "core::ptr::null_mut()".to_string(),
        FieldType::Array(_, length) => format!("[0; {length}]"),
        FieldType::Named(name) => format!("{}::ZERO", rust_name(tables, name).unwrap_or(name)),
    }
}

fn render_record(out: &mut String, tables: &Tables, record: &RecordDef) -> Result<()> {
    let layouts = layouts(tables, ARCHES[0])?;
    let computed = layouts
        .computed
        .get(&record.name)
        .with_context(|| format!("record {} was not computed", record.name))?;
    if let Some(doc) = &record.doc {
        let _ = writeln!(out, "/// {doc}");
    }
    let _ = writeln!(out, "#[repr(C)]");
    let _ = writeln!(out, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
    let _ = writeln!(out, "pub struct {} {{", record.rust);
    for (field, defined) in computed.fields.iter().zip(&record.fields) {
        if let Some(doc) = &defined.doc {
            let _ = writeln!(out, "    /// {doc}");
        }
        let _ = writeln!(
            out,
            "    pub {}: {},",
            field.name,
            rust_type(tables, &field.ty)
        );
    }
    let _ = writeln!(out, "}}");
    out.push('\n');
    let _ = writeln!(out, "impl {} {{", record.rust);
    let _ = writeln!(out, "    /// All-zero value.");
    let _ = writeln!(out, "    pub const ZERO: Self = Self {{");
    for field in &computed.fields {
        let _ = writeln!(
            out,
            "        {}: {},",
            field.name,
            zero_value(tables, &field.ty)
        );
    }
    let _ = writeln!(out, "    }};");
    let _ = writeln!(out, "}}");
    out.push('\n');
    write_assertion(out, &record.rust, record.size, record.align);
    for field in &computed.fields {
        let _ = writeln!(
            out,
            "const _: () = assert!(core::mem::offset_of!({}, {}) == {});",
            record.rust, field.name, field.offset
        );
    }
    out.push('\n');
    Ok(())
}

fn render_opaque(out: &mut String, tables: &Tables, opaque: &OpaqueDef) -> Result<()> {
    let shared = opaque.size.is_shared() && opaque.align.is_shared();
    if shared {
        render_one_opaque(out, opaque, ARCHES[0], None)?;
    } else {
        for arch in ARCHES {
            render_one_opaque(out, opaque, arch, Some(arch))?;
        }
    }
    let _ = tables;
    Ok(())
}

fn render_one_opaque(
    out: &mut String,
    opaque: &OpaqueDef,
    arch: &str,
    cfg: Option<&str>,
) -> Result<()> {
    let layout = opaque_layout(opaque, arch)?;
    if let Some(arch) = cfg {
        let _ = writeln!(out, "#[cfg(target_arch = \"{arch}\")]");
    }
    if let Some(doc) = &opaque.doc {
        let _ = writeln!(out, "/// {doc}");
    }
    let _ = writeln!(out, "/// C: `{}`", opaque.c);
    if layout.align > 8 {
        let _ = writeln!(out, "#[repr(C, align({}))]", layout.align);
    } else {
        let _ = writeln!(out, "#[repr(C)]");
    }
    let _ = writeln!(out, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
    let (element, count, _, _) = crate::layout::rust_opaque_body(opaque, arch)?;
    let _ = writeln!(out, "pub struct {} {{", opaque.rust);
    let _ = writeln!(out, "    /// Opaque bytes.");
    let _ = writeln!(out, "    pub bytes: [{element}; {count}],");
    let _ = writeln!(out, "}}");
    out.push('\n');
    if let Some(arch) = cfg {
        let _ = writeln!(out, "#[cfg(target_arch = \"{arch}\")]");
    }
    let _ = writeln!(out, "impl {} {{", opaque.rust);
    let _ = writeln!(out, "    /// All-zero value.");
    let _ = writeln!(
        out,
        "    pub const ZERO: Self = Self {{ bytes: [0; {count}] }};"
    );
    let _ = writeln!(out, "}}");
    out.push('\n');
    if let Some(arch) = cfg {
        let _ = writeln!(out, "#[cfg(target_arch = \"{arch}\")]");
    }
    write_assertion(out, &opaque.rust, layout.size, layout.align);
    out.push('\n');
    Ok(())
}

fn render_layout_table(tables: &Tables) -> Result<String> {
    let mut out = first_party_generated("structs.toml");
    out.push('\n');
    out.push_str("//! `repr(C)` layout table for the current target, built from `size_of` and `offset_of!`.\n\n");
    out.push_str("use crate::layout::{FieldLayout, StructLayout};\n\n");
    let mut structs = String::new();
    for record in &tables.structs.record {
        let layouts = layouts(tables, ARCHES[0])?;
        let computed = layouts
            .computed
            .get(&record.name)
            .with_context(|| format!("record {} was not computed", record.name))?;
        let _ = writeln!(structs, "    StructLayout {{");
        let _ = writeln!(structs, "        name: \"{}\",", record.name);
        let _ = writeln!(structs, "        c_name: \"{}\",", record.c);
        let _ = writeln!(
            structs,
            "        size: core::mem::size_of::<{}>(),",
            record.rust
        );
        let _ = writeln!(
            structs,
            "        align: core::mem::align_of::<{}>(),",
            record.rust
        );
        let _ = writeln!(structs, "        fields: &[");
        for field in &computed.fields {
            let _ = writeln!(structs, "            FieldLayout {{");
            let _ = writeln!(structs, "                name: \"{}\",", field.name);
            let _ = writeln!(
                structs,
                "                offset: core::mem::offset_of!({}, {}),",
                record.rust, field.name
            );
            let _ = writeln!(structs, "                size: {},", field.size);
            let _ = writeln!(structs, "            }},");
        }
        let _ = writeln!(structs, "        ],");
        let _ = writeln!(structs, "    }},");
    }
    // Import only the types the table names. One line per type keeps the file rustfmt-clean
    // without emulating rustfmt's packing of a long brace group.
    let mut imports: Vec<&str> = tables
        .structs
        .record
        .iter()
        .map(|record| record.rust.as_str())
        .collect();
    imports.sort_unstable();
    imports.dedup();
    for import in imports {
        let _ = writeln!(out, "use crate::generated::structs::{import};");
    }
    out.push('\n');
    out.push_str("/// Every record of the external ABI, in table order.\n");
    out.push_str("pub const STRUCTS: &[StructLayout] = &[\n");
    out.push_str(&structs);
    out.push_str("];\n");
    Ok(out)
}

fn render_group(
    out: &mut String,
    def: &crate::model::ConstFile,
    stem: &str,
    values: &crate::validate::Values,
) -> Result<()> {
    let mut sorted: Vec<&ConstDef> = def.consts.iter().collect();
    sorted.sort_by(|left, right| left.name.cmp(&right.name));
    if sorted
        .iter()
        .any(|constant| constant.name.chars().any(char::is_lowercase))
    {
        out.push_str("#![allow(non_upper_case_globals)]\n\n");
    }
    for constant in &sorted {
        let Some(value) = values.by_name.get(&constant.name) else {
            bail!("{stem}: {} was not evaluated", constant.name);
        };
        render_doc(out, constant);
        if let Some(visible) = &constant.visible {
            let _ = writeln!(out, "/// visible: {visible}");
        }
        if !constant.arch.is_empty() {
            let _ = writeln!(out, "#[cfg({})]", arch_cfg(&constant.arch));
        }
        let ty = constant.ty.as_deref().unwrap_or(&def.rust_type);
        let rendered = values::render_rust(constant, value.value, &def.base);
        let _ = writeln!(out, "pub const {}: {ty} = {rendered};", constant.name);
    }
    out.push('\n');
    out.push_str("/// Every entry of this group as `(name, value)`, sorted by name.\n");
    out.push_str("pub const ALL: &[(&str, i128)] = &[\n");
    for constant in &sorted {
        let Some(value) = values.by_name.get(&constant.name) else {
            continue;
        };
        if !constant.arch.is_empty() {
            let _ = writeln!(out, "    #[cfg({})]", arch_cfg(&constant.arch));
        }
        let _ = writeln!(
            out,
            "    (\"{}\", {}),",
            constant.name,
            render_i128(value.value)
        );
    }
    out.push_str("];\n");
    let _ = def;
    Ok(())
}

fn write_assertion(out: &mut String, rust: &str, size: i64, align: i64) {
    let condition = format!(
        "core::mem::size_of::<{rust}>() == {size} && core::mem::align_of::<{rust}>() == {align}"
    );
    let line = format!("const _: () = assert!({condition});");
    if line.len() <= 100 {
        let _ = writeln!(out, "{line}");
        return;
    }
    let indented = format!("    assert!({condition});");
    if indented.len() <= 100 {
        let _ = writeln!(out, "const _: () =");
        let _ = writeln!(out, "{indented}");
    } else {
        let _ = writeln!(out, "const _: () = assert!(");
        if condition.len() > 96
            && let Some((left, right)) = condition.split_once(" && ")
        {
            let _ = writeln!(out, "    {left}");
            let _ = writeln!(out, "        && {right}");
        } else {
            let _ = writeln!(out, "    {condition}");
        }
        let _ = writeln!(out, ");");
    }
}

fn arch_cfg(arches: &[String]) -> String {
    if arches.len() == 1 {
        format!("target_arch = \"{}\"", arches[0])
    } else {
        format!(
            "any({})",
            arches
                .iter()
                .map(|arch| format!("target_arch = \"{arch}\""))
                .collect::<Vec<_>>()
                .join(", ")
        )
    }
}

fn render_doc(out: &mut String, constant: &ConstDef) {
    if let Some(text) = &constant.doc {
        let _ = writeln!(out, "/// {text}");
    }
}

