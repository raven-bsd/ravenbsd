//! Rendering of the constant parts of `abi/generated/include/bits/*.h`.

use std::fmt::Write as _;

use anyhow::Result;

use crate::model::ConstDef;
use crate::provenance::{CommentStyle, musl_notice};
use crate::validate::{Tables, expected_header};
use crate::values;

/// Render every constant header, keyed by the path under `abi/generated/include`.
pub fn render_all(
    tables: &Tables,
    values: &crate::validate::Values,
    musl_rev: &str,
) -> Result<std::collections::BTreeMap<String, String>> {
    let mut files = std::collections::BTreeMap::new();
    for group in &tables.groups {
        let upstream = group.def.source.join(", ");
        let mut out = musl_notice(CommentStyle::BlockC, &upstream, musl_rev);
        out.push('\n');
        let _ = writeln!(
            out,
            "/* Generated by raven-libc-hdrgen from abi/{}.toml. Do not edit. */",
            group.stem
        );
        out.push('\n');
        let header = expected_header(&group.stem);
        let _ = writeln!(out, "#ifndef {}", group.def.guard);
        let _ = writeln!(out, "#define {}", group.def.guard);
        out.push('\n');
        let mut sorted: Vec<&ConstDef> = group.def.consts.iter().collect();
        sorted.sort_by(|left, right| left.name.cmp(&right.name));
        let mut conditional: Option<String> = None;
        for constant in sorted {
            let Some(value) = values.by_name.get(&constant.name) else {
                continue;
            };
            let condition = condition_of(constant);
            if condition != conditional {
                if conditional.is_some() {
                    out.push_str("#endif\n");
                }
                if let Some(condition) = &condition {
                    let _ = writeln!(out, "#if {condition}");
                }
                conditional = condition;
            }
            if let Some(text) = &constant.doc {
                let _ = writeln!(out, "/* {text} */");
            }
            if let Some(visible) = &constant.visible {
                let _ = writeln!(out, "/* visible: {visible} */");
            }
            let rendered = values::render_c(constant, value.value, &group.def.base);
            if let Some(alias) = &constant.alias {
                let _ = writeln!(out, "#define {} {alias}", constant.name);
            } else {
                let _ = writeln!(out, "#define {} {rendered}", constant.name);
            }
        }
        if conditional.is_some() {
            out.push_str("#endif\n");
        }
        out.push('\n');
        let _ = writeln!(out, "#endif /* {} */", group.def.guard);
        files.insert(header, out);
    }
    Ok(files)
}

fn condition_of(constant: &ConstDef) -> Option<String> {
    let arch = if constant.arch.is_empty() {
        None
    } else {
        let parts: Vec<String> = constant.arch.iter().map(|arch| arch_macro(arch)).collect();
        Some(format!("defined({})", parts.join(") || defined(")))
    };
    let visible = constant
        .visible
        .as_ref()
        .map(|class| format!("__{}_VISIBLE", class.to_ascii_uppercase()));
    match (arch, visible) {
        (None, None) => None,
        (Some(arch), None) => Some(arch),
        (None, Some(visible)) => Some(visible),
        (Some(arch), Some(visible)) => Some(format!("{arch} && {visible}")),
    }
}

fn arch_macro(arch: &str) -> String {
    match arch {
        "x86_64" => "__x86_64__".to_string(),
        "aarch64" => "__aarch64__".to_string(),
        "riscv64" => "__riscv".to_string(),
        other => format!("__{other}__"),
    }
}

