"""S178 host runner for the thread/futex conformance topic.

Builds the Rust probe, packs the release initfs, overlays the probe and its one-shot service,
boots QEMU with the requested accelerator and four CPUs, then evaluates the shared row contract
from ``tests/conformance/harness/runner.py``.

Why a topic-local runner: ``tests/conformance/harness/runner.py`` writes its qtest case without
``qemu_extra``, so it can only run the default TCG image.  This ticket's gate needs KVM and TCG
four-CPU runs, so the topic supplies the accelerator while reusing the harness tables, parser and
verdict logic unchanged.

Exit codes: 0 every gate row passed and every controlled mutation turned its row red; 1 a gate
row failed (or, in ``--phase mutation``, the targeted row turned red = mutation caught); 2 a
build/image/QEMU failure, never a pass.

Usage:
  python3 tests/conformance/threads/run.py --accel tcg
  python3 tests/conformance/threads/run.py --accel kvm
  python3 tests/conformance/threads/run.py --accel kvm --phase mutation --mutation wake-one-extra
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
TOPIC = "threads"
PROBE_GUEST = "/bin/conformance-probe"
SERVICE = "threads-conformance"

sys.path.insert(0, str(ROOT / "tests/conformance/harness"))
import runner as harness  # noqa: E402  (path set above)


class StepError(Exception):
    """A build/image/QEMU failure, never a row verdict."""


def run_step(label: str, argv: list[str], timeout: int) -> tuple[int, str]:
    print(f"conformance: step={label} argv={argv} timeout={timeout}", flush=True)
    completed = subprocess.run(
        ["timeout", str(timeout), *argv],
        cwd=ROOT,
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        check=False,
    )
    output = completed.stdout or ""
    print(output, end="" if output.endswith("\n") else "\n", flush=True)
    return completed.returncode, output


def write_case(accel: str, initfs: Path, timeout: int, case: Path) -> Path:
    extra = []
    if accel == "kvm":
        extra = ["-enable-kvm", "-cpu", "host"]
    text = "\n".join(
        [
            "# SPDX-License-Identifier: BSD-3-Clause",
            "# Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors",
            "# Generated by tests/conformance/threads/run.py.",
            f'name = "{SERVICE}-{accel}"',
            'arch = "x86_64"',
            'profile = "release"',
            f"timeout_secs = {timeout}",
            f'initfs = "{initfs.relative_to(ROOT)}"',
            'boot_cmdline = "console=ttyS0 test-exit=1 smp_user=on"',
            f"qemu_extra = {json.dumps(extra)}",
            'expect_exit = "any"',
            "",
            "[[expect]]",
            f"regex = 'CONFORM {TOPIC} begin'",
            "",
            "[[expect]]",
            f"regex = 'CONFORM {TOPIC} done failures=[0-9]+'",
            "",
            "[[forbid]]",
            "regex = '(?i)panic|EXCEPTION'",
            "",
        ]
    )
    case.write_text(text, encoding="utf-8")
    return case


def execute(args: argparse.Namespace, topic_dir: Path) -> dict[str, object]:
    out = ROOT / "build" / "conformance" / TOPIC
    out.mkdir(parents=True, exist_ok=True)
    probe = out / "conformance-probe"

    code, _ = run_step("probe-build", ["sh", str((topic_dir / "build.sh").relative_to(ROOT))], 180)
    if code != 0:
        raise StepError(f"probe build failed rc={code}")
    if not probe.is_file():
        raise StepError(f"probe build produced no {probe}")

    code, _ = run_step(
        "initfs", ["cargo", "xtask", "initfs", "--arch", "x86_64", "--profile", "release"], 480
    )
    if code != 0:
        raise StepError(f"initfs build failed rc={code}")
    base = ROOT / "build/x86_64/initfs.img"
    if not base.is_file():
        raise StepError(f"initfs produced no {base}")

    overlay = out / f"initfs-{args.accel}.img"
    svcd = out / f"svcd-{args.accel}.conf"
    svcd.write_text(
        "# SPDX-License-Identifier: BSD-3-Clause\n"
        "# Copyright (c) 2026, Bo Maryniuk and RavenBSD contributors\n"
        "# Generated by tests/conformance/threads/run.py.\n"
        f"exit_when_exits = {SERVICE}\n",
        encoding="utf-8",
    )
    code, _ = run_step(
        "overlay",
        [
            "target/debug/raven-b70-overlay",
            str(base.relative_to(ROOT)),
            str(overlay.relative_to(ROOT)),
            f"{PROBE_GUEST}={probe.relative_to(ROOT)}:0755",
            f"/etc/services.d/{SERVICE}.toml={(topic_dir / f'{SERVICE}.service.toml').relative_to(ROOT)}:0644",
            f"/etc/svcd.conf={svcd.relative_to(ROOT)}:0644",
        ],
        60,
    )
    if code != 0:
        raise StepError(f"overlay failed rc={code}")

    case = write_case(args.accel, overlay, args.guest_timeout, out / f"{args.accel}.toml")
    code, output = run_step(
        "qtest",
        ["cargo", "xtask", "qtest", "--case", str(case.relative_to(ROOT))],
        args.guest_timeout + 240,
    )
    log = ROOT / "build" / "qtest" / f"{SERVICE}-{args.accel}.log"
    if not log.is_file():
        raise StepError(f"qtest produced no serial log at {log}")
    text = log.read_text(encoding="utf-8", errors="replace")
    (out / f"{args.accel}.serial.log").write_text(text, encoding="utf-8")
    if code != 0:
        tail = "\n".join(output.splitlines()[-20:])
        raise StepError(f"qtest failed rc={code}: {tail}")

    return harness.parse_log(text, TOPIC)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--accel", choices=("kvm", "tcg"), default="tcg")
    parser.add_argument("--profile", default="release", help="informational; must be release")
    parser.add_argument("--phase", choices=("normal", "mutation", "all"), default="all")
    parser.add_argument("--mutation", help="mutation name for --phase mutation")
    parser.add_argument("--guest-timeout", type=int, default=180)
    args = parser.parse_args()
    if args.phase == "mutation" and not args.mutation:
        parser.error("--phase mutation requires --mutation")

    topic_dir = ROOT / "tests/conformance" / TOPIC
    rows = harness.read_table(topic_dir / "rows.tsv")
    mutations = harness.read_mutations(topic_dir / "mutations.tsv")
    try:
        parsed = execute(args, topic_dir)
    except (StepError, harness.HarnessError) as error:
        print(f"conformance: HARNESS-ERROR {error}", file=sys.stderr, flush=True)
        return 2

    normal = harness.evaluate(parsed, rows, mutations, "normal", None)
    mutation_results = {
        item["name"]: harness.evaluate(parsed, rows, mutations, "mutation", item["name"])
        for item in mutations
    }
    summary = {
        "topic": TOPIC,
        "accel": args.accel,
        "phase": args.phase,
        "rows": parsed["rows"],
        "mutations": {
            key: value["rows"] for key, value in parsed["mutations"].items()
        },
        "normal_reasons": normal,
        "mutation_reasons": mutation_results,
    }
    out = ROOT / "build" / "conformance" / TOPIC
    (out / f"result-{args.accel}.json").write_text(
        json.dumps(summary, indent=2) + "\n", encoding="utf-8"
    )

    if normal:
        print(f"conformance: FAIL reasons={';'.join(normal)}", flush=True)
    else:
        print(f"conformance: PASS topic={TOPIC} accel={args.accel} rows={len(parsed['rows'])}", flush=True)
    for name, reasons in mutation_results.items():
        if reasons:
            print(f"conformance: MUTATION-NOT-CAUGHT mutation={name} reasons={';'.join(reasons)}", flush=True)
        else:
            print(f"conformance: MUTATION-CAUGHT mutation={name}", flush=True)

    if args.phase == "mutation":
        reasons = mutation_results[args.mutation]
        if reasons:
            infra = any(
                marker in reason
                for reason in reasons
                for marker in ("missing-section", "unknown", "end=missing", "!=failures=")
            )
            return 2 if infra else 0
        return 1
    if args.phase == "normal":
        return 0 if not normal else 1
    caught = all(not reasons for reasons in mutation_results.values())
    return 0 if not normal and caught else 1


if __name__ == "__main__":
    raise SystemExit(main())
